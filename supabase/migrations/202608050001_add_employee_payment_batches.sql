begin;

create table public.payroll_payment_batches(
  id bigint generated by default as identity primary key,
  payroll_month date not null unique check(payroll_month=date_trunc('month',payroll_month)::date),
  status text not null check(status in('paying','completed')),
  target_employee_count integer not null check(target_employee_count>0),
  paid_employee_count integer not null default 0 check(paid_employee_count>=0 and paid_employee_count<=target_employee_count),
  calculated_net_total bigint not null default 0,
  actual_paid_total bigint not null default 0,
  difference_total bigint not null default 0,
  employee_insurance_total bigint not null default 0,
  employer_insurance_total bigint not null default 0,
  director_insurance_amount bigint not null default 0,
  insurance_remittance_total bigint not null default 0,
  actual_company_cost_total bigint not null default 0,
  engine_version text not null,
  common_settings_snapshot jsonb not null,
  started_by bigint not null references public.users(id),
  started_at timestamptz not null default now(),
  completed_by bigint null references public.users(id),
  completed_at timestamptz null,
  updated_at timestamptz not null default now(),
  constraint payroll_payment_batches_completion_check check(
    (status='paying' and completed_by is null and completed_at is null) or
    (status='completed' and completed_by is not null and completed_at is not null and paid_employee_count=target_employee_count)
  )
);

create table public.payroll_employee_payments(
  id bigint generated by default as identity primary key,
  payroll_batch_id bigint not null references public.payroll_payment_batches(id) on delete restrict,
  user_id bigint not null references public.users(id) on delete restrict,
  employee_name text not null,
  part_snapshot text null,
  position_snapshot text null,
  employee_snapshot jsonb not null,
  payment_status text not null default 'unpaid' check(payment_status in('unpaid','paid')),
  calculation_snapshot jsonb null,
  calculation_hash text null,
  calculated_net_amount bigint null,
  actual_paid_amount bigint null,
  difference_amount bigint null,
  difference_reason text null,
  employee_insurance_amount bigint null,
  employer_insurance_amount bigint null,
  payment_date date null,
  paid_by bigint null references public.users(id),
  paid_at timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint payroll_employee_payments_unique unique(payroll_batch_id,user_id),
  constraint payroll_employee_payments_state_check check(
    (payment_status='unpaid' and calculation_snapshot is null and calculation_hash is null and calculated_net_amount is null and actual_paid_amount is null and difference_amount is null and difference_reason is null and employee_insurance_amount is null and employer_insurance_amount is null and payment_date is null and paid_by is null and paid_at is null) or
    (payment_status='paid' and calculation_snapshot is not null and calculation_hash is not null and calculated_net_amount is not null and actual_paid_amount>0 and difference_amount=actual_paid_amount-calculated_net_amount and employee_insurance_amount is not null and employer_insurance_amount is not null and payment_date is not null and paid_by is not null and paid_at is not null and (difference_amount=0 or nullif(btrim(difference_reason),'') is not null))
  )
);
create index payroll_employee_payments_batch_status_idx on public.payroll_employee_payments(payroll_batch_id,payment_status);

create table public.payroll_payment_audit_logs(
  id bigint generated by default as identity primary key,
  payroll_batch_id bigint not null references public.payroll_payment_batches(id) on delete restrict,
  employee_payment_id bigint null references public.payroll_employee_payments(id) on delete restrict,
  action text not null check(action in('batch_started','employee_paid','employee_payment_cancelled','batch_completed')),
  actor_user_id bigint not null references public.users(id),
  reason text null,
  before_snapshot jsonb null,
  after_snapshot jsonb null,
  created_at timestamptz not null default now()
);
create index payroll_payment_audit_batch_created_idx on public.payroll_payment_audit_logs(payroll_batch_id,created_at desc);

alter table public.payroll_payment_batches enable row level security;
alter table public.payroll_employee_payments enable row level security;
alter table public.payroll_payment_audit_logs enable row level security;
revoke all on table public.payroll_payment_batches,public.payroll_employee_payments,public.payroll_payment_audit_logs from public,anon,authenticated,service_role;
revoke all on sequence public.payroll_payment_batches_id_seq,public.payroll_employee_payments_id_seq,public.payroll_payment_audit_logs_id_seq from public,anon,authenticated,service_role;
grant select,insert,update on table public.payroll_payment_batches,public.payroll_employee_payments,public.payroll_payment_audit_logs to service_role;
grant usage,select on sequence public.payroll_payment_batches_id_seq,public.payroll_employee_payments_id_seq,public.payroll_payment_audit_logs_id_seq to service_role;

create function public.payroll_pay_employee_v1(
  p_month date,p_targets jsonb,p_user_id bigint,p_calculation_snapshot jsonb,p_calculation_hash text,
  p_calculated_net_amount bigint,p_actual_paid_amount bigint,p_difference_reason text,p_payment_date date,
  p_actor_user_id bigint,p_engine_version text,p_common_settings_snapshot jsonb,p_director_insurance_amount bigint
) returns jsonb language plpgsql security definer set search_path=public as $$
declare v_run public.payroll_payment_batches%rowtype;v_employee public.payroll_employee_payments%rowtype;v_target jsonb;v_now timestamptz:=now();v_paid integer;v_before jsonb;
begin
  perform public.payroll_assert_actor_v2(p_actor_user_id);
  if p_month>=date_trunc('month',timezone('Asia/Ho_Chi_Minh',now()))::date then raise exception 'PAYROLL_MONTH_NOT_CLOSED' using errcode='55000';end if;
  if p_month<>date_trunc('month',p_month)::date or jsonb_typeof(p_targets)<>'array' or jsonb_array_length(p_targets)=0 then raise exception 'PAYROLL_INVALID_PAYMENT_REQUEST' using errcode='22023';end if;
  if exists(select 1 from jsonb_array_elements(p_targets) as target(value) where coalesce((target.value->>'isPayable')::boolean,false)=false or jsonb_array_length(coalesce(target.value->'failureCodes','[]'::jsonb))>0) then raise exception 'PAYROLL_BATCH_PREFLIGHT_FAILED' using errcode='55000';end if;
  if p_actual_paid_amount<=0 or p_calculated_net_amount is null or p_calculation_snapshot is null or nullif(btrim(p_calculation_hash),'') is null or p_payment_date is null then raise exception 'PAYROLL_INVALID_PAYMENT_REQUEST' using errcode='22023';end if;
  if p_actual_paid_amount<>p_calculated_net_amount and nullif(btrim(p_difference_reason),'') is null then raise exception 'PAYROLL_PAYMENT_REASON_REQUIRED' using errcode='22023';end if;
  perform pg_advisory_xact_lock(82118,(extract(year from p_month)::integer*100+extract(month from p_month)::integer));
  select * into v_run from public.payroll_payment_batches where payroll_month=p_month for update;
  if not found then
    insert into public.payroll_payment_batches(payroll_month,status,target_employee_count,engine_version,common_settings_snapshot,started_by,director_insurance_amount)
    values(p_month,'paying',jsonb_array_length(p_targets),p_engine_version,p_common_settings_snapshot,p_actor_user_id,greatest(p_director_insurance_amount,0)) returning * into v_run;
    for v_target in select value from jsonb_array_elements(p_targets) loop
      insert into public.payroll_employee_payments(payroll_batch_id,user_id,employee_name,part_snapshot,position_snapshot,employee_snapshot)
      values(v_run.id,(v_target->>'userId')::bigint,v_target->>'employeeName',v_target->>'part',v_target->>'position',v_target);
    end loop;
    insert into public.payroll_payment_audit_logs(payroll_batch_id,action,actor_user_id,after_snapshot) values(v_run.id,'batch_started',p_actor_user_id,to_jsonb(v_run));
  elsif v_run.status='completed' then raise exception 'PAYROLL_BATCH_COMPLETED' using errcode='55000';
  end if;
  perform pg_advisory_xact_lock(82119,p_user_id::integer);
  select * into v_employee from public.payroll_employee_payments where payroll_batch_id=v_run.id and user_id=p_user_id for update;
  if not found then raise exception 'PAYROLL_EMPLOYEE_NOT_IN_BATCH' using errcode='22023';end if;
  if v_employee.payment_status='paid' then raise exception 'PAYROLL_EMPLOYEE_ALREADY_PAID' using errcode='23505';end if;
  update public.payroll_employee_payments set payment_status='paid',calculation_snapshot=p_calculation_snapshot,calculation_hash=p_calculation_hash,
    calculated_net_amount=p_calculated_net_amount,actual_paid_amount=p_actual_paid_amount,difference_amount=p_actual_paid_amount-p_calculated_net_amount,
    difference_reason=case when p_actual_paid_amount=p_calculated_net_amount then null else btrim(p_difference_reason) end,
    employee_insurance_amount=coalesce((p_calculation_snapshot#>>'{employee,amounts,employeeInsuranceDeductionAmount}')::bigint,0),
    employer_insurance_amount=coalesce((p_calculation_snapshot#>>'{employee,amounts,employerInsuranceAmount}')::bigint,0),payment_date=p_payment_date,paid_by=p_actor_user_id,paid_at=v_now,updated_at=v_now
  where id=v_employee.id returning * into v_employee;
  insert into public.payroll_payment_audit_logs(payroll_batch_id,employee_payment_id,action,actor_user_id,reason,after_snapshot)
  values(v_run.id,v_employee.id,'employee_paid',p_actor_user_id,v_employee.difference_reason,to_jsonb(v_employee));
  select count(*) filter(where payment_status='paid')::integer into v_paid from public.payroll_employee_payments where payroll_batch_id=v_run.id;
  update public.payroll_payment_batches r set paid_employee_count=v_paid,calculated_net_total=x.calculated,actual_paid_total=x.actual,difference_total=x.difference,
    employee_insurance_total=x.employee_insurance,employer_insurance_total=x.employer_insurance,
    insurance_remittance_total=x.employee_insurance+x.employer_insurance+r.director_insurance_amount,
    actual_company_cost_total=x.actual+x.employee_insurance+x.employer_insurance+r.director_insurance_amount,updated_at=v_now
  from(select coalesce(sum(calculated_net_amount),0)::bigint calculated,coalesce(sum(actual_paid_amount),0)::bigint actual,coalesce(sum(difference_amount),0)::bigint difference,
    coalesce(sum(employee_insurance_amount),0)::bigint employee_insurance,coalesce(sum(employer_insurance_amount),0)::bigint employer_insurance
    from public.payroll_employee_payments where payroll_batch_id=v_run.id and payment_status='paid')x where r.id=v_run.id returning r.* into v_run;
  if v_paid=v_run.target_employee_count then
    v_before:=to_jsonb(v_run);
    update public.payroll_payment_batches set status='completed',completed_by=p_actor_user_id,completed_at=v_now,updated_at=v_now where id=v_run.id returning * into v_run;
    insert into public.payroll_payment_audit_logs(payroll_batch_id,action,actor_user_id,before_snapshot,after_snapshot) values(v_run.id,'batch_completed',p_actor_user_id,v_before,to_jsonb(v_run));
  end if;
  return jsonb_build_object('runId',v_run.id,'status',v_run.status,'employee',to_jsonb(v_employee));
end $$;

create function public.payroll_cancel_employee_payment_v1(p_run_id bigint,p_user_id bigint,p_reason text,p_actor_user_id bigint)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_run public.payroll_payment_batches%rowtype;v_employee public.payroll_employee_payments%rowtype;v_before jsonb;v_paid integer;
begin
  perform public.payroll_assert_actor_v2(p_actor_user_id);
  if nullif(btrim(p_reason),'') is null then raise exception 'PAYROLL_PAYMENT_CANCEL_REASON_REQUIRED' using errcode='22023';end if;
  select * into v_run from public.payroll_payment_batches where id=p_run_id for update;
  if not found then raise exception 'PAYROLL_RUN_NOT_FOUND';end if;
  if v_run.status<>'paying' then raise exception 'PAYROLL_BATCH_COMPLETED' using errcode='55000';end if;
  select * into v_employee from public.payroll_employee_payments where payroll_batch_id=p_run_id and user_id=p_user_id for update;
  if not found or v_employee.payment_status<>'paid' then raise exception 'PAYROLL_EMPLOYEE_NOT_PAID' using errcode='22023';end if;
  v_before:=to_jsonb(v_employee);
  update public.payroll_employee_payments set payment_status='unpaid',calculation_snapshot=null,calculation_hash=null,calculated_net_amount=null,actual_paid_amount=null,difference_amount=null,difference_reason=null,employee_insurance_amount=null,employer_insurance_amount=null,payment_date=null,paid_by=null,paid_at=null,updated_at=now() where id=v_employee.id returning * into v_employee;
  insert into public.payroll_payment_audit_logs(payroll_batch_id,employee_payment_id,action,actor_user_id,reason,before_snapshot,after_snapshot) values(p_run_id,v_employee.id,'employee_payment_cancelled',p_actor_user_id,btrim(p_reason),v_before,to_jsonb(v_employee));
  select count(*) filter(where payment_status='paid')::integer into v_paid from public.payroll_employee_payments where payroll_batch_id=p_run_id;
  update public.payroll_payment_batches r set paid_employee_count=v_paid,calculated_net_total=x.calculated,actual_paid_total=x.actual,difference_total=x.difference,employee_insurance_total=x.employee_insurance,employer_insurance_total=x.employer_insurance,insurance_remittance_total=x.employee_insurance+x.employer_insurance+r.director_insurance_amount,actual_company_cost_total=x.actual+x.employee_insurance+x.employer_insurance+r.director_insurance_amount,updated_at=now()
  from(select coalesce(sum(calculated_net_amount),0)::bigint calculated,coalesce(sum(actual_paid_amount),0)::bigint actual,coalesce(sum(difference_amount),0)::bigint difference,coalesce(sum(employee_insurance_amount),0)::bigint employee_insurance,coalesce(sum(employer_insurance_amount),0)::bigint employer_insurance from public.payroll_employee_payments where payroll_batch_id=p_run_id and payment_status='paid')x where r.id=p_run_id returning r.* into v_run;
  return jsonb_build_object('runId',v_run.id,'status',v_run.status,'employee',to_jsonb(v_employee));
end $$;

create function public.payroll_lock_paid_month_adjustments_v1() returns trigger language plpgsql security definer set search_path=public as $$
begin
  perform pg_advisory_xact_lock(82119,new.user_id::integer);
  if exists(select 1 from public.payroll_payment_batches r join public.payroll_employee_payments e on e.payroll_batch_id=r.id where r.payroll_month=new.payroll_month and e.user_id=new.user_id and e.payment_status='paid') then raise exception 'PAYROLL_ADJUSTMENT_LOCKED_FOR_PAID_EMPLOYEE' using errcode='55000';end if;
  return new;
end $$;
create trigger payroll_monthly_adjustments_paid_lock before insert or update on public.payroll_monthly_adjustments for each row execute function public.payroll_lock_paid_month_adjustments_v1();

revoke all on function public.payroll_pay_employee_v1(date,jsonb,bigint,jsonb,text,bigint,bigint,text,date,bigint,text,jsonb,bigint) from public,anon,authenticated;
revoke all on function public.payroll_cancel_employee_payment_v1(bigint,bigint,text,bigint) from public,anon,authenticated;
revoke all on function public.payroll_lock_paid_month_adjustments_v1() from public,anon,authenticated;
grant execute on function public.payroll_pay_employee_v1(date,jsonb,bigint,jsonb,text,bigint,bigint,text,date,bigint,text,jsonb,bigint) to service_role;
grant execute on function public.payroll_cancel_employee_payment_v1(bigint,bigint,text,bigint) to service_role;

commit;
