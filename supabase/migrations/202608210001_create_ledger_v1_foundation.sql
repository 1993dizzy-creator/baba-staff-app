create table public.ledger_fund_accounts (
  id bigint generated by default as identity primary key,
  code text not null unique check (code ~ '^[a-z0-9_]+$'),
  type text not null check (type in ('cash','bank','personal_custody','card_clearing','other')),
  holder_name text null,
  display_name text not null check (length(btrim(display_name)) > 0),
  is_active boolean not null default true,
  active_from date not null,
  active_to date null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  constraint ledger_fund_account_active_period check (active_to is null or active_to >= active_from)
);

create table public.ledger_categories (
  id bigint generated by default as identity primary key,
  name text not null check (length(btrim(name)) > 0),
  kind text not null check (kind in ('income','expense')),
  parent_id bigint null references public.ledger_categories(id) on delete restrict,
  cost_behavior text not null default 'none' check (cost_behavior in ('fixed','variable','semi_variable','none')),
  inventory_category_id bigint null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint ledger_category_not_self_parent check (parent_id is null or parent_id <> id),
  constraint ledger_category_name_kind_unique unique (kind,name)
);

create table public.ledger_parties (
  id bigint generated by default as identity primary key,
  name text not null check (length(btrim(name)) > 0),
  type text not null check (type in ('supplier','customer','employee','owner','government','utility','other')),
  default_category_id bigint null references public.ledger_categories(id) on delete restrict,
  default_payment_cycle text null,
  is_active boolean not null default true,
  memo text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.ledger_transactions (
  id bigint generated by default as identity primary key,
  operation_id uuid not null,
  type text not null check (type in ('expense','income','transfer','opening','balance_adjustment','investment','owner_settlement','card_settlement')),
  occurred_at timestamptz not null,
  business_date date not null,
  recognition_month date null,
  amount numeric(16,0) not null check (amount > 0 and amount = trunc(amount)),
  category_id bigint null references public.ledger_categories(id) on delete restrict,
  party_id bigint null references public.ledger_parties(id) on delete restrict,
  status text not null default 'confirmed' check (status in ('draft','confirmed','cancelled','corrected')),
  source_type text not null default 'manual' check (length(btrim(source_type)) > 0),
  source_key text null,
  source_snapshot jsonb not null default '{}'::jsonb check (jsonb_typeof(source_snapshot) = 'object'),
  correction_of_id bigint null references public.ledger_transactions(id) on delete restrict,
  memo text null,
  created_by bigint not null references public.users(id) on delete restrict,
  confirmed_by bigint null references public.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ledger_transaction_recognition_policy check (
    (type in ('income','expense') and recognition_month is not null and recognition_month = date_trunc('month',recognition_month)::date and category_id is not null)
    or (type not in ('income','expense') and recognition_month is null and category_id is null)
  ),
  constraint ledger_transaction_confirmation_actor check ((status = 'confirmed' and confirmed_by is not null) or status <> 'confirmed'),
  constraint ledger_transaction_not_self_correction check (correction_of_id is null or correction_of_id <> id)
);

