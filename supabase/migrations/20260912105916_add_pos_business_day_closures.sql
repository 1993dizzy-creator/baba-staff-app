create table public.pos_sales_business_day_closures (
  id bigint generated by default as identity primary key,
  business_date date not null,
  revision integer not null check (revision > 0),
  close_method text not null check (close_method in ('manual', 'automatic')),
  closed_at timestamptz not null default now(),
  closed_by bigint not null references public.users(id) on delete restrict,
  sync_run_id bigint null references public.pos_sales_sync_runs(id) on delete restrict,
  source_fingerprint text not null check (source_fingerprint ~ '^[0-9a-f]{64}$'),
  source_snapshot jsonb not null check (jsonb_typeof(source_snapshot) = 'object'),
  ledger_result_snapshot jsonb not null default '{}'::jsonb check (jsonb_typeof(ledger_result_snapshot) = 'object'),
  created_at timestamptz not null default now(),
  unique (business_date, revision)
);
create index pos_sales_business_day_closures_actor_idx on public.pos_sales_business_day_closures(closed_by);
create index pos_sales_business_day_closures_sync_run_idx on public.pos_sales_business_day_closures(sync_run_id) where sync_run_id is not null;
alter table public.pos_sales_business_day_closures enable row level security;
revoke all on table public.pos_sales_business_day_closures from public, anon, authenticated, service_role;
revoke all on sequence public.pos_sales_business_day_closures_id_seq from public, anon, authenticated, service_role;
grant select on table public.pos_sales_business_day_closures to service_role;

create schema pos_sales_close_private;
revoke all on schema pos_sales_close_private from public, anon, authenticated, service_role;
-- Unforgeable transaction-local projection capability. Only the close RPC
-- owner can create it; it is removed before returning and rolled back on error.
create table pos_sales_close_private.projection_permissions (
  transaction_id bigint not null,
  business_date date not null,
  actor_user_id bigint not null references public.users(id),
  primary key (transaction_id, business_date)
);
revoke all on table pos_sales_close_private.projection_permissions from public, anon, authenticated, service_role;

create function pos_sales_close_private.canonical_json(p_value jsonb)
returns text language plpgsql immutable set search_path = pg_catalog, public as $$
declare v_result text;
begin
  case jsonb_typeof(p_value)
    when 'object' then
      select '{' || coalesce(string_agg(to_jsonb(key)::text || ':' || pos_sales_close_private.canonical_json(value), ',' order by key collate "C"), '') || '}'
      into v_result from jsonb_each(p_value);
    when 'array' then
      select '[' || coalesce(string_agg(pos_sales_close_private.canonical_json(value), ',' order by ordinal), '') || ']'
      into v_result from jsonb_array_elements(p_value) with ordinality a(value, ordinal);
    when 'number' then
      if (p_value::text)::numeric <> trunc((p_value::text)::numeric)
        or abs((p_value::text)::numeric) > 9007199254740991 then
        raise exception 'POS_SOURCE_INVALID_AMOUNT' using errcode = '22023';
      end if;
      v_result := ((p_value::text)::numeric)::bigint::text;
    else v_result := p_value::text;
  end case;
  if v_result is null then raise exception 'POS_SOURCE_SNAPSHOT_INCOMPLETE' using errcode = '22023'; end if;
  return v_result;
end $$;

create function pos_sales_close_private.validate_source(p_date date, p_fingerprint text, p_snapshot jsonb, p_rows jsonb)
returns void language plpgsql set search_path = pg_catalog, public as $$
declare v_live jsonb;
begin
  if p_fingerprint is null or p_fingerprint !~ '^[0-9a-f]{64}$'
    or jsonb_typeof(p_snapshot) is distinct from 'object'
    or jsonb_typeof(p_rows) is distinct from 'array' then
    raise exception 'POS_SOURCE_SNAPSHOT_INCOMPLETE' using errcode = '22023';
  end if;
  v_live := pos_sales_close_private.build_source(p_date);
  if p_rows is distinct from v_live->'rows' or p_snapshot is distinct from v_live->'sourceSnapshot'
    or p_fingerprint is distinct from v_live->>'sourceFingerprint' then
    raise exception 'POS_SOURCE_CHANGED_BEFORE_PROJECTION' using errcode = '40001';
  end if;
end $$;

