create function public.payroll_create_attendance_bonus_eligibility_version_v1(
  p_user_id bigint,
  p_is_eligible boolean,
  p_effective_month date,
  p_actor_user_id bigint,
  p_note text default null
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_current_month date := date_trunc('month', now() at time zone 'Asia/Ho_Chi_Minh')::date;
  v_revision bigint;
  v_target public.users%rowtype;
  v_created public.payroll_attendance_bonus_eligibility_versions%rowtype;
begin
  perform public.payroll_assert_actor_v2(p_actor_user_id);
  if p_is_eligible is null then
    raise exception 'ATTENDANCE_BONUS_INVALID_ELIGIBILITY' using errcode = '22023';
  end if;
  if p_effective_month is null
    or p_effective_month <> date_trunc('month', p_effective_month)::date
    or p_effective_month < v_current_month then
    raise exception 'ATTENDANCE_BONUS_INVALID_EFFECTIVE_MONTH' using errcode = '22023';
  end if;

  select * into v_target from public.users
  where id = p_user_id and is_system_account = false for share;
  if not found then raise exception 'USER_NOT_FOUND' using errcode = 'P0002'; end if;
  if p_is_eligible and v_target.attendance_tracking_enabled is distinct from true then
    raise exception 'ATTENDANCE_BONUS_REQUIRES_ATTENDANCE_TRACKING' using errcode = '22023';
  end if;

  perform pg_advisory_xact_lock(hashtext('payroll_attendance_bonus_eligibility_versions:' || p_user_id::text));
  select coalesce(max(revision), 0) + 1 into v_revision
  from public.payroll_attendance_bonus_eligibility_versions where user_id = p_user_id;
  insert into public.payroll_attendance_bonus_eligibility_versions (
    user_id, is_eligible, effective_month, revision, created_by, note
  ) values (
    p_user_id, p_is_eligible, p_effective_month, v_revision, p_actor_user_id,
    nullif(btrim(p_note), '')
  ) returning * into v_created;
  return to_jsonb(v_created);
end;
$$;

revoke all on function public.payroll_create_attendance_bonus_eligibility_version_v1(
