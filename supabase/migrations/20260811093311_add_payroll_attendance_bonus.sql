create table public.payroll_attendance_bonus_policy_versions (
  id bigint generated by default as identity primary key,
  effective_month date not null,
  minimum_actual_workdays integer not null,
  allowed_late_count integer not null,
  allowed_early_leave_count integer not null,
  bonus_amount numeric(16,0) not null,
  revision bigint not null,
