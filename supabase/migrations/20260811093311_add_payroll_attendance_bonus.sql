create function public.payroll_create_attendance_bonus_policy_version_v1(
  p_effective_month date,
  p_minimum_actual_workdays integer,
  p_allowed_late_count integer,
  p_allowed_early_leave_count integer,
  p_bonus_amount numeric,
  p_actor_user_id bigint,
  p_note text default null
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_current_month date := date_trunc('month', now() at time zone 'Asia/Ho_Chi_Minh')::date;
  v_revision bigint;
  v_created public.payroll_attendance_bonus_policy_versions%rowtype;
begin
  perform public.payroll_assert_actor_v2(p_actor_user_id);
  if p_effective_month is null
    or p_effective_month <> date_trunc('month', p_effective_month)::date
    or p_effective_month < v_current_month then
    raise exception 'ATTENDANCE_BONUS_INVALID_EFFECTIVE_MONTH' using errcode = '22023';
  end if;
  if p_minimum_actual_workdays is null or p_minimum_actual_workdays <= 0 then
    raise exception 'ATTENDANCE_BONUS_INVALID_MINIMUM_WORKDAYS' using errcode = '22023';
  end if;
  if p_allowed_late_count is null or p_allowed_late_count < 0
    or p_allowed_early_leave_count is null or p_allowed_early_leave_count < 0 then
    raise exception 'ATTENDANCE_BONUS_INVALID_ALLOWANCE_COUNTS' using errcode = '22023';
  end if;
  if p_bonus_amount is null or p_bonus_amount <= 0 or p_bonus_amount <> trunc(p_bonus_amount) then
    raise exception 'ATTENDANCE_BONUS_INVALID_AMOUNT' using errcode = '22023';
  end if;

  perform pg_advisory_xact_lock(hashtext('payroll_attendance_bonus_policy_versions'));
  select coalesce(max(revision), 0) + 1 into v_revision
  from public.payroll_attendance_bonus_policy_versions;
  insert into public.payroll_attendance_bonus_policy_versions (
    effective_month, minimum_actual_workdays, allowed_late_count,
    allowed_early_leave_count, bonus_amount, revision, created_by, note
  ) values (
    p_effective_month, p_minimum_actual_workdays, p_allowed_late_count,
    p_allowed_early_leave_count, p_bonus_amount, v_revision, p_actor_user_id,
    nullif(btrim(p_note), '')
  ) returning * into v_created;
  return to_jsonb(v_created);
end;
$$;

revoke all on function public.payroll_create_attendance_bonus_policy_version_v1(
  date, integer, integer, integer, numeric, bigint, text
) from public, anon, authenticated;
grant execute on function public.payroll_create_attendance_bonus_policy_version_v1(
  date, integer, integer, integer, numeric, bigint, text
