    check (minimum_actual_workdays > 0),
  constraint payroll_attendance_bonus_policy_late_count_check
    check (allowed_late_count >= 0),
  constraint payroll_attendance_bonus_policy_early_count_check
    check (allowed_early_leave_count >= 0),
  constraint payroll_attendance_bonus_policy_amount_check
    check (bonus_amount > 0 and bonus_amount = trunc(bonus_amount)),
  constraint payroll_attendance_bonus_policy_revision_check check (revision >= 1),
  constraint payroll_attendance_bonus_policy_revision_unique unique (revision)
