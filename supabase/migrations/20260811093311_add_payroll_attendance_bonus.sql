create function public.users_block_attendance_tracking_disable_when_bonus_eligible()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_current_month date := date_trunc('month', now() at time zone 'Asia/Ho_Chi_Minh')::date;
  v_has_eligible boolean;
begin
  if old.attendance_tracking_enabled is distinct from true
    or new.attendance_tracking_enabled is distinct from false then
    return new;
  end if;
  select exists (
    select 1 from (
      (select is_eligible
       from public.payroll_attendance_bonus_eligibility_versions
       where user_id = new.id and effective_month <= v_current_month
       order by effective_month desc, revision desc limit 1)
      union all
      (select distinct on (effective_month) is_eligible
       from public.payroll_attendance_bonus_eligibility_versions
       where user_id = new.id and effective_month > v_current_month
       order by effective_month, revision desc)
    ) resolved where resolved.is_eligible
  ) into v_has_eligible;
  if v_has_eligible then
    raise exception 'ATTENDANCE_BONUS_ELIGIBLE_BLOCKS_ATTENDANCE_TRACKING_DISABLE'
      using errcode = '55000';
  end if;
  return new;
end;
$$;

create trigger users_block_attendance_tracking_disable_when_bonus_eligible
  before update on public.users for each row
  execute function public.users_block_attendance_tracking_disable_when_bonus_eligible();

revoke all on function public.users_block_attendance_tracking_disable_when_bonus_eligible()
  from public, anon, authenticated;

commit;

