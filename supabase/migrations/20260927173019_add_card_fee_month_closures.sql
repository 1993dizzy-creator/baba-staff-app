-- Month-end card fee closures.
--
-- Card deposits are allocated to sale principal FIFO (auto_allocated) and never estimate a
-- fee. Once every card deposit for a sale month has been registered, a user confirms that
-- month: whatever card sale gross is still outstanding at that moment becomes the month's
-- card fee. The amount is always recomputed here under lock; it is never user input.
--
-- Card sale outstanding is now:
--   POS card sale gross
--   - non-cancelled ledger_card_reconciliation_lines (deposits, incl. historical matched)
--   - non-cancelled ledger_card_fee_allocation_lines (month-end fee)
-- Historical matched differences (card_settlement_difference) are untouched: their gross
-- is already consumed by reconciliation lines, so it is never counted again as fee.
--
-- No existing rows are updated and no closure is created for any month by this migration.

create table public.ledger_card_fee_closures(
  id bigint generated by default as identity primary key,
  fee_month date not null check (fee_month = date_trunc('month', fee_month)::date),
  fee_amount numeric(16,3) not null check (fee_amount >= 0),
  expense_transaction_id bigint null unique references public.ledger_transactions(id) on delete restrict,
  status text not null default 'confirmed' check (status in ('confirmed', 'cancelled')),
  confirmed_at timestamptz not null default now(),
  confirmed_by bigint not null references public.users(id) on delete restrict,
  cancelled_at timestamptz null,
  cancelled_by bigint null references public.users(id) on delete restrict,
  cancel_reason text null,
  memo text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- A zero fee still records that the month's card deposits were checked; it books nothing.
  constraint ledger_card_fee_closure_expense check (
    (fee_amount = 0 and expense_transaction_id is null) or (fee_amount > 0 and expense_transaction_id is not null)
  ),
  constraint ledger_card_fee_closure_cancellation check (
    (status = 'cancelled' and cancelled_at is not null and cancelled_by is not null and nullif(btrim(cancel_reason), '') is not null)
    or (status = 'confirmed' and cancelled_at is null and cancelled_by is null and cancel_reason is null)
  )
);
-- At most one active closure per sale month; cancelled history is kept and can be re-confirmed.
create unique index ledger_card_fee_closures_active_month_idx
  on public.ledger_card_fee_closures(fee_month) where status = 'confirmed';
create index ledger_card_fee_closures_month_idx on public.ledger_card_fee_closures(fee_month, status);
create index ledger_card_fee_closures_confirmed_by_idx on public.ledger_card_fee_closures(confirmed_by);
create index ledger_card_fee_closures_cancelled_by_idx on public.ledger_card_fee_closures(cancelled_by);

create table public.ledger_card_fee_allocation_lines(
  id bigint generated by default as identity primary key,
  closure_id bigint not null references public.ledger_card_fee_closures(id) on delete restrict,
  pos_card_transaction_id bigint not null references public.ledger_transactions(id) on delete restrict,
  allocated_fee_amount numeric(16,3) not null check (allocated_fee_amount > 0),
  created_at timestamptz not null default now(),
  constraint ledger_card_fee_allocation_line_unique unique (closure_id, pos_card_transaction_id)
);
create index ledger_card_fee_allocation_lines_closure_idx on public.ledger_card_fee_allocation_lines(closure_id);
create index ledger_card_fee_allocation_lines_pos_transaction_idx on public.ledger_card_fee_allocation_lines(pos_card_transaction_id);

alter table public.ledger_card_fee_closures enable row level security;
alter table public.ledger_card_fee_allocation_lines enable row level security;
revoke all on table public.ledger_card_fee_closures, public.ledger_card_fee_allocation_lines from public, anon, authenticated, service_role;
revoke all on sequence public.ledger_card_fee_closures_id_seq, public.ledger_card_fee_allocation_lines_id_seq from public, anon, authenticated, service_role;
grant select on table public.ledger_card_fee_closures, public.ledger_card_fee_allocation_lines to service_role;

