  perform pg_advisory_xact_lock(hashtext('pos_sales_business_day_close:' || p_business_date::text));
  if public.ledger_month_is_closed_v1(date_trunc('month', p_business_date)::date) then
    return jsonb_build_object('status', 'month_closed');
  end if;
  lock table public.pos_sales_receipts, public.pos_sales_receipt_payments in share mode;
  perform pos_sales_close_private.validate_source(p_business_date, p_source_fingerprint, p_source_snapshot, p_rows);
  if p_sync_run_id is not null and not exists (
    select 1 from public.pos_sales_sync_runs where id = p_sync_run_id and business_date = p_business_date and status = 'success'
  ) then raise exception 'POS_SALES_SUCCESSFUL_SYNC_RUN_REQUIRED' using errcode = '22023'; end if;

  select * into v_existing from public.pos_sales_business_day_closures
  where business_date = p_business_date order by revision desc limit 1 for update;
  if v_existing.id is not null and v_existing.source_fingerprint = p_source_fingerprint then
    return jsonb_build_object('status', 'already_closed', 'closureId', v_existing.id, 'revision', v_existing.revision);
  end if;
  if v_existing.id is not null and v_role = 'manager' then
    return jsonb_build_object('status', 'forbidden');
  end if;
  if v_existing.id is not null and not p_manual_reclose then
    return jsonb_build_object('status', 'source_changed_after_close', 'closureId', v_existing.id,
      'revision', v_existing.revision, 'closedFingerprint', v_existing.source_fingerprint, 'currentFingerprint', p_source_fingerprint);
  end if;

  if v_existing.id is not null then
    select r into v_old_card from jsonb_array_elements(v_existing.source_snapshot->'rows') r where r->>'bucket' = 'card';
    select r into v_new_card from jsonb_array_elements(p_rows) r where r->>'bucket' = 'card';
    if v_old_card is null or v_new_card is null then
      raise exception 'POS_SOURCE_SNAPSHOT_INCOMPLETE' using errcode = '22023';
    end if;
    if v_old_card->>'fingerprint' is distinct from v_new_card->>'fingerprint'
      or (v_old_card->>'amount')::numeric is distinct from (v_new_card->>'amount')::numeric then
      -- Card reconciliation also locks these POS transactions before allocating.
      -- Holding this row lock makes the settlement check/projection atomic.
      -- Preserve the legacy projector's advisory-key-before-row lock order.
      perform pg_advisory_xact_lock(hashtext('ledger_pos_sync:pos:' || p_business_date::text || ':card'));
      perform 1 from public.ledger_transactions
      where source_type = 'pos_sales_daily_payment' and business_date = p_business_date
        and source_key = 'pos:' || p_business_date::text || ':card'
      order by id for update;
      if exists (
        select 1 from public.ledger_card_reconciliation_lines l
        join public.ledger_card_reconciliations r on r.id = l.reconciliation_id
        join public.ledger_transactions t on t.id = l.pos_card_transaction_id
        where t.source_type = 'pos_sales_daily_payment' and t.business_date = p_business_date
          and t.source_key = 'pos:' || p_business_date::text || ':card'
          and r.status <> 'cancelled'
      ) or exists (
        select 1 from public.ledger_card_fee_allocation_lines f
        join public.ledger_card_fee_closures c on c.id = f.closure_id
        join public.ledger_transactions t on t.id = f.pos_card_transaction_id
        where t.source_type = 'pos_sales_daily_payment' and t.business_date = p_business_date
          and t.source_key = 'pos:' || p_business_date::text || ':card'
          and c.status <> 'cancelled'
      ) or exists (
        select 1 from public.ledger_card_fee_closures c
        where c.status = 'confirmed' and c.fee_month = date_trunc('month', p_business_date)::date
      ) then
        return jsonb_build_object('status', 'card_settlement_locked', 'closureId', v_existing.id, 'revision', v_existing.revision);
      end if;
    end if;
  end if;

  insert into pos_sales_close_private.projection_permissions values (txid_current(), p_business_date, p_actor_user_id);
  v_result := pos_sales_close_private.project_business_day(p_rows, p_actor_user_id);
  if v_result->>'status' is distinct from 'ok' or coalesce((v_result->>'closedMonth')::boolean, false) then
    -- v1 can return a failure after writing earlier buckets. Raising aborts the
    -- entire close transaction, including projection, audit and capability.
    raise exception 'POS_SALES_LEDGER_PROJECTION_FAILED: %', v_result using errcode = 'P0001';
  end if;
  -- Verify the actual projection, including the zero-amount corrected case.
  if exists (
    select 1 from jsonb_array_elements(p_rows) r
    left join public.ledger_transactions t on t.source_type = 'pos_sales_daily_payment'
      and t.source_key = 'pos:' || p_business_date::text || ':' || (r->>'bucket')
    where ((r->>'amount')::numeric > 0 and (t.id is null or t.status <> 'confirmed'
      or t.amount <> (r->>'amount')::numeric or t.source_fingerprint <> r->>'fingerprint'
      or (select coalesce(sum(m.amount), 0) from public.ledger_movements m where m.transaction_id = t.id) <> t.amount))
      or ((r->>'amount')::numeric = 0 and t.status = 'confirmed')
  ) then raise exception 'POS_SALES_LEDGER_PROJECTION_INCOMPLETE' using errcode = 'P0001'; end if;

  delete from pos_sales_close_private.projection_permissions where transaction_id = txid_current() and business_date = p_business_date;
  v_revision := coalesce(v_existing.revision, 0) + 1;
  insert into public.pos_sales_business_day_closures(business_date, revision, close_method, closed_at,
    closed_by, sync_run_id, source_fingerprint, source_snapshot, ledger_result_snapshot)
  values (p_business_date, v_revision, p_close_method, v_now, p_actor_user_id, p_sync_run_id,
    p_source_fingerprint, p_source_snapshot, v_result) returning id into v_id;
  insert into public.ledger_audit_logs(actor_user_id, action, entity_type, entity_id, after_snapshot, reason)
  values (p_actor_user_id, 'pos_sales_day_closed', 'pos_sales_day_closure', v_id,
    jsonb_build_object('businessDate', p_business_date, 'revision', v_revision,
      'previousClosureId', v_existing.id, 'sourceFingerprint', p_source_fingerprint, 'closeMethod', p_close_method),
    case when v_existing.id is null then 'Initial business day close' else 'Explicit manual reclose' end);
  return jsonb_build_object('status', case when v_existing.id is null then 'closed' else 'reclosed' end,
    'closureId', v_id, 'revision', v_revision, 'ledgerResult', v_result);
end $$;

