insert into public.employee_work_schedule_versions (
  user_id, start_time, end_time, unpaid_break_minutes, effective_from, effective_to, revision, created_by, change_reason
)
select id, work_start_time::time, work_end_time::time, 0, date '2026-08-01', null, 1, null, 'Initial seed from users work hours'
from public.users
where work_start_time ~ '^(?:[01][0-9]|2[0-3]):[0-5][0-9]$'
  and work_end_time ~ '^(?:[01][0-9]|2[0-3]):[0-5][0-9]$'
on conflict (user_id, revision) do nothing;

create or replace function public.employee_create_work_schedule_version_v1(
  p_user_id bigint,
  p_start_time time without time zone,
  p_end_time time without time zone,
  p_unpaid_break_minutes integer,
  p_effective_from date,
  p_actor_user_id bigint,
  p_change_reason text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_previous public.employee_work_schedule_versions%rowtype;
  v_created public.employee_work_schedule_versions%rowtype;
  v_revision bigint;
  v_vietnam_today date := (clock_timestamp() at time zone 'Asia/Ho_Chi_Minh')::date;
begin
  if v_vietnam_today < date '2026-08-01' or p_effective_from <> v_vietnam_today then
    return jsonb_build_object('status', 'invalid_effective_from');
  end if;
  perform 1 from public.users where id = p_actor_user_id and is_active = true and role in ('owner', 'master');
  if not found then return jsonb_build_object('status', 'forbidden'); end if;
  perform 1 from public.users where id = p_user_id;
  if not found then return jsonb_build_object('status', 'user_not_found'); end if;
  perform pg_advisory_xact_lock(-p_user_id);
  select * into v_previous from public.employee_work_schedule_versions
    where user_id = p_user_id and effective_to is null
    order by effective_from desc limit 1 for update;
  if found and p_effective_from <= v_previous.effective_from then
    return jsonb_build_object('status', 'period_conflict');
  end if;
  select coalesce(max(revision), 0) + 1 into v_revision
    from public.employee_work_schedule_versions where user_id = p_user_id;
  if v_previous.id is not null then
    update public.employee_work_schedule_versions set effective_to = p_effective_from where id = v_previous.id;
  end if;
  insert into public.employee_work_schedule_versions (
    user_id,start_time,end_time,unpaid_break_minutes,effective_from,revision,created_by,change_reason
  ) values (
    p_user_id,p_start_time,p_end_time,p_unpaid_break_minutes,p_effective_from,v_revision,p_actor_user_id,nullif(btrim(p_change_reason),'')
  ) returning * into v_created;
  if p_effective_from = v_vietnam_today then
    update public.users
      set work_start_time = to_char(p_start_time, 'HH24:MI'),
          work_end_time = to_char(p_end_time, 'HH24:MI')
      where id = p_user_id;
    if not found then return jsonb_build_object('status', 'user_not_found'); end if;
  end if;
  return jsonb_build_object('status','created','schedule',to_jsonb(v_created));
exception when exclusion_violation or unique_violation then
  return jsonb_build_object('status','period_conflict');
end
$$;

revoke all on function public.employee_create_work_schedule_version_v1(bigint,time without time zone,time without time zone,integer,date,bigint,text) from public, anon, authenticated;
grant execute on function public.employee_create_work_schedule_version_v1(bigint,time without time zone,time without time zone,integer,date,bigint,text) to service_role;

create or replace function public.payroll_create_contract_version_v1(
