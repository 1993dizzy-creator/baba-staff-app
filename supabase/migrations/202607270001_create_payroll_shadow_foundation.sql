create table public.employee_work_schedule_versions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete restrict,
  start_time time without time zone not null,
  end_time time without time zone not null,
  unpaid_break_minutes integer not null default 0 check (unpaid_break_minutes between 0 and 720),
  effective_from date not null,
  effective_to date null,
  revision bigint not null,
  created_by bigint null references public.users(id),
  created_at timestamptz not null default now(),
  change_reason text null,
  constraint employee_schedule_valid_range check (effective_to is null or effective_to > effective_from),
  constraint employee_schedule_revision_unique unique (user_id, revision),
  constraint employee_schedule_no_overlap exclude using gist (
    user_id with =,
    daterange(effective_from, coalesce(effective_to, 'infinity'::date), '[)') with &&
  )
);

create table public.payroll_contract_versions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete restrict,
  pay_type text not null check (pay_type in ('monthly', 'daily', 'hourly')),
  calculation_basis text not null check (calculation_basis in ('minute', 'hour', 'day')),
  base_salary numeric(16,0) not null check (base_salary >= 0),
  standard_workdays numeric(6,2) null check (standard_workdays > 0),
  standard_minutes_per_day integer not null check (standard_minutes_per_day between 1 and 1440),
  time_block_minutes integer not null default 1 check (time_block_minutes between 1 and 1440),
  rounding_mode text not null default 'none' check (rounding_mode in ('none', 'floor', 'ceil', 'nearest')),
  late_adjustment_mode text not null default 'separate' check (late_adjustment_mode in ('separate', 'deduct_minutes', 'ignore')),
  early_leave_adjustment_mode text not null default 'separate' check (early_leave_adjustment_mode in ('separate', 'deduct_minutes', 'ignore')),
  overtime_mode text not null default 'requires_approval' check (overtime_mode in ('requires_approval', 'ignore')),
  paid_leave_mode text not null default 'manual_review' check (paid_leave_mode in ('manual_review', 'paid', 'unpaid')),
  effective_from date not null,
  effective_to date null,
  revision bigint not null,
  created_by bigint not null references public.users(id),
  created_at timestamptz not null default now(),
  note text null,
  constraint payroll_contract_pay_basis_check check (not (pay_type = 'hourly' and calculation_basis = 'day')),
  constraint payroll_contract_valid_range check (effective_to is null or effective_to > effective_from),
  constraint payroll_contract_revision_unique unique (user_id, revision),
  constraint payroll_contract_no_overlap exclude using gist (
    user_id with =,
    daterange(effective_from, coalesce(effective_to, 'infinity'::date), '[)') with &&
  )
);

