  if p_effective_from < date '2026-08-01' then
    return jsonb_build_object('status', 'invalid_effective_from');
  end if;
  if p_pay_type = 'hourly' and p_calculation_basis = 'day' then
    return jsonb_build_object('status', 'invalid_pay_basis');
  end if;
  if p_base_salary <> trunc(p_base_salary) then
    return jsonb_build_object('status', 'invalid_base_salary');
  end if;
  perform 1 from public.users where id = p_actor_user_id and is_active = true and role in ('owner', 'master');
  if not found then return jsonb_build_object('status', 'forbidden'); end if;
  perform 1 from public.users where id = p_user_id;
  if not found then return jsonb_build_object('status', 'user_not_found'); end if;
  perform pg_advisory_xact_lock(p_user_id);
  select * into v_previous from public.payroll_contract_versions
    where user_id = p_user_id and effective_to is null
    order by effective_from desc limit 1 for update;
  if found and p_effective_from <= v_previous.effective_from then
    return jsonb_build_object('status', 'period_conflict');
  end if;
  select coalesce(max(revision), 0) + 1 into v_revision
    from public.payroll_contract_versions where user_id = p_user_id;
  if v_previous.id is not null then
    update public.payroll_contract_versions set effective_to = p_effective_from where id = v_previous.id;
  end if;
  insert into public.payroll_contract_versions (
    user_id,pay_type,calculation_basis,base_salary,standard_workdays,
    standard_minutes_per_day,time_block_minutes,rounding_mode,
    late_adjustment_mode,early_leave_adjustment_mode,overtime_mode,
    paid_leave_mode,effective_from,revision,created_by,note
  ) values (
    p_user_id,p_pay_type,p_calculation_basis,p_base_salary,p_standard_workdays,
    p_standard_minutes_per_day,p_time_block_minutes,p_rounding_mode,
    p_late_adjustment_mode,p_early_leave_adjustment_mode,p_overtime_mode,
    p_paid_leave_mode,p_effective_from,v_revision,p_actor_user_id,nullif(btrim(p_note), '')
  ) returning * into v_created;
  insert into public.payroll_contract_audit_logs(contract_version_id,user_id,action,actor_user_id,snapshot,reason)
  values(v_created.id,p_user_id,'created',p_actor_user_id,to_jsonb(v_created),nullif(btrim(p_note),''));
  return jsonb_build_object('status','created','contract',to_jsonb(v_created));
exception when exclusion_violation or unique_violation then
  return jsonb_build_object('status','period_conflict');
end
$$;

