-- Annual store rent: contracts and their actual payments.
--
-- A contract records the lease terms (period, annual amount, monthly expense,
-- payment method and due date). A payment row links a contract to money that
-- was actually paid:
--   * source 'ledger'     -> an existing confirmed prepaid_expense_payment
--                            ledger transaction (UNIQUE: one contract per payment)
--   * source 'pre_ledger' -> evidence of a payment made before the app ledger
--                            opened (e.g. Sheet row). Its cash effect is already
--                            inside the opening balance seed, so it never books a
--                            transaction or a movement.
--
-- Nothing here writes ledger_transactions, ledger_movements, reserve entries,
-- recurring plans or month closures. Monthly rent expense keeps coming from the
-- recurring plan (ledger_sync_recurring_expenses_*), unchanged.

create table public.ledger_rent_contracts (
  id bigint generated by default as identity primary key,
  name text not null check (length(btrim(name)) between 1 and 120),
  lessor_name text null check (lessor_name is null or length(btrim(lessor_name)) between 1 and 120),
  period_start date not null,
  period_end date not null,
  annual_amount numeric(16, 3) not null check (annual_amount > 0 and scale(annual_amount) <= 3),
  monthly_expense_amount numeric(16, 3) null
    check (monthly_expense_amount is null or (monthly_expense_amount > 0 and scale(monthly_expense_amount) <= 3)),
  status text not null check (status in ('planned', 'active', 'ended')),
  terms_status text not null default 'provisional' check (terms_status in ('provisional', 'confirmed')),
  payment_method text null check (payment_method is null or payment_method in ('lump_sum', 'installments', 'other')),
  payment_due_date date null,
  payment_terms_note text null check (payment_terms_note is null or length(payment_terms_note) <= 500),
  recurring_plan_id bigint null references public.ledger_recurring_expense_plans(id) on delete restrict,
  reserve_plan_id bigint null references public.ledger_reserve_plans(id) on delete restrict,
  memo text null check (memo is null or length(memo) <= 500),
  created_by bigint null references public.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ledger_rent_contracts_period check (period_end >= period_start)
);

-- A reserve plan funds at most one contract.
create unique index ledger_rent_contracts_reserve_plan_unique
  on public.ledger_rent_contracts(reserve_plan_id) where reserve_plan_id is not null;
create index ledger_rent_contracts_period_idx on public.ledger_rent_contracts(period_start);

create table public.ledger_rent_contract_payments (
  id bigint generated by default as identity primary key,
  contract_id bigint not null references public.ledger_rent_contracts(id) on delete restrict,
  source text not null check (source in ('ledger', 'pre_ledger')),
  payment_transaction_id bigint null references public.ledger_transactions(id) on delete restrict,
  -- Evidence key of a pre-ledger payment (e.g. 'sheet:2026-07:row:33'). Kept when the
  -- row is later converted to a ledger link, so the same evidence can never be
  -- recorded twice.
  pre_ledger_reference text null
    check (pre_ledger_reference is null or length(btrim(pre_ledger_reference)) between 1 and 200),
  paid_on date not null,
  amount numeric(16, 3) not null check (amount > 0 and scale(amount) <= 3),
  fund_account_id bigint null references public.ledger_fund_accounts(id) on delete restrict,
  memo text null check (memo is null or length(memo) <= 500),
  created_by bigint null references public.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ledger_rent_contract_payments_source_shape check (
    (source = 'ledger' and payment_transaction_id is not null)
    or (source = 'pre_ledger' and payment_transaction_id is null and pre_ledger_reference is not null)
  )
);

create unique index ledger_rent_contract_payments_tx_unique
  on public.ledger_rent_contract_payments(payment_transaction_id) where payment_transaction_id is not null;
create unique index ledger_rent_contract_payments_reference_unique
  on public.ledger_rent_contract_payments(pre_ledger_reference) where pre_ledger_reference is not null;
create index ledger_rent_contract_payments_contract_idx
  on public.ledger_rent_contract_payments(contract_id, paid_on);

alter table public.ledger_rent_contracts enable row level security;
alter table public.ledger_rent_contract_payments enable row level security;
revoke all on table public.ledger_rent_contracts from public, anon, authenticated, service_role;
revoke all on table public.ledger_rent_contract_payments from public, anon, authenticated, service_role;
revoke all on sequence public.ledger_rent_contracts_id_seq from public, anon, authenticated, service_role;
revoke all on sequence public.ledger_rent_contract_payments_id_seq from public, anon, authenticated, service_role;
grant select on table public.ledger_rent_contracts to service_role;
grant select on table public.ledger_rent_contract_payments to service_role;

comment on table public.ledger_rent_contracts is
  'Store lease contracts. Display/management only: never books ledger transactions, movements or reserve entries.';
comment on table public.ledger_rent_contract_payments is
  'Actual rent payments of a contract: a linked prepaid_expense_payment (source=ledger) or pre-ledger evidence whose cash is already in the opening balance (source=pre_ledger).';

-- Same write roles as the other ledger RPCs: an active owner/master app user.
create function public.ledger_rent_actor_can_write_v1(p_actor_user_id bigint)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select exists (
    select 1 from public.users
    where id = p_actor_user_id and is_active = true and app_login_enabled = true
      and lower(role::text) in ('owner', 'master')
  )
$$;

-- The first day of the app ledger = the opening balance seed's business date.
create function public.ledger_rent_ledger_start_v1()
returns date
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select min(business_date) from public.ledger_transactions
  where type = 'opening' and status = 'confirmed'
$$;

-- Create (p_contract_id null) or update a contract. Payload keys:
-- name, lessorName, periodStart, periodEnd, annualAmount, monthlyExpenseAmount,
-- status, termsStatus, paymentMethod, paymentDueDate, paymentTermsNote,
-- recurringPlanId, reservePlanId, memo.
create function public.ledger_save_rent_contract_v1(
  p_contract_id bigint,
  p_payload jsonb,
  p_actor_user_id bigint
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_before public.ledger_rent_contracts%rowtype;
  v_id bigint;
  v_name text;
  v_lessor text;
  v_start date;
  v_end date;
  v_annual numeric;
  v_monthly numeric;
  v_status text;
  v_terms text;
  v_method text;
  v_due date;
  v_terms_note text;
  v_recurring bigint;
  v_reserve bigint;
  v_memo text;
  v_after jsonb;
begin
  if not public.ledger_rent_actor_can_write_v1(p_actor_user_id) then
    return jsonb_build_object('status', 'forbidden');
  end if;
  if p_payload is null or jsonb_typeof(p_payload) <> 'object' then
    return jsonb_build_object('status', 'invalid_payload');
  end if;

  begin
    v_name := nullif(btrim(p_payload->>'name'), '');
    v_lessor := nullif(btrim(p_payload->>'lessorName'), '');
    v_start := (p_payload->>'periodStart')::date;
    v_end := (p_payload->>'periodEnd')::date;
    v_annual := (p_payload->>'annualAmount')::numeric;
    v_monthly := nullif(p_payload->>'monthlyExpenseAmount', '')::numeric;
    v_status := p_payload->>'status';
    v_terms := coalesce(p_payload->>'termsStatus', 'provisional');
    v_method := nullif(p_payload->>'paymentMethod', '');
    v_due := nullif(p_payload->>'paymentDueDate', '')::date;
    v_terms_note := nullif(btrim(p_payload->>'paymentTermsNote'), '');
    v_recurring := nullif(p_payload->>'recurringPlanId', '')::bigint;
    v_reserve := nullif(p_payload->>'reservePlanId', '')::bigint;
    v_memo := nullif(btrim(p_payload->>'memo'), '');
  exception when others then
    return jsonb_build_object('status', 'invalid_payload');
  end;

  if v_name is null or v_start is null or v_end is null or v_end < v_start
    or v_annual is null or v_annual <= 0 or scale(v_annual) > 3
    or (v_monthly is not null and (v_monthly <= 0 or scale(v_monthly) > 3))
    or v_status is null or v_status not in ('planned', 'active', 'ended')
    or v_terms not in ('provisional', 'confirmed')
    or (v_method is not null and v_method not in ('lump_sum', 'installments', 'other')) then
    return jsonb_build_object('status', 'invalid_payload');
  end if;

  -- Serializes contract writes so the overlap check below cannot race.
  perform pg_advisory_xact_lock(hashtext('ledger_rent_contracts'));

  if v_recurring is not null and not exists (select 1 from public.ledger_recurring_expense_plans where id = v_recurring) then
    return jsonb_build_object('status', 'invalid_recurring_plan');
  end if;
  if v_reserve is not null and not exists (select 1 from public.ledger_reserve_plans where id = v_reserve) then
    return jsonb_build_object('status', 'invalid_reserve_plan');
  end if;
  if exists (
    select 1 from public.ledger_rent_contracts c
    where c.id is distinct from p_contract_id
      and c.period_start <= v_end and c.period_end >= v_start
  ) then
    return jsonb_build_object('status', 'period_overlap');
  end if;
  if v_reserve is not null and exists (
    select 1 from public.ledger_rent_contracts c
    where c.reserve_plan_id = v_reserve and c.id is distinct from p_contract_id
  ) then
    return jsonb_build_object('status', 'reserve_plan_in_use');
  end if;

  if p_contract_id is null then
    insert into public.ledger_rent_contracts(
      name, lessor_name, period_start, period_end, annual_amount, monthly_expense_amount,
      status, terms_status, payment_method, payment_due_date, payment_terms_note,
      recurring_plan_id, reserve_plan_id, memo, created_by
    ) values (
      v_name, v_lessor, v_start, v_end, v_annual, v_monthly,
      v_status, v_terms, v_method, v_due, v_terms_note,
      v_recurring, v_reserve, v_memo, p_actor_user_id
    ) returning id into v_id;
  else
    select * into v_before from public.ledger_rent_contracts where id = p_contract_id for update;
    if v_before.id is null then
      return jsonb_build_object('status', 'not_found');
    end if;
    -- Payments already linked must still fit inside the contract amount.
    if (select coalesce(sum(amount), 0) from public.ledger_rent_contract_payments where contract_id = p_contract_id) > v_annual then
      return jsonb_build_object('status', 'payments_exceed_contract_amount');
    end if;
    update public.ledger_rent_contracts set
      name = v_name, lessor_name = v_lessor, period_start = v_start, period_end = v_end,
      annual_amount = v_annual, monthly_expense_amount = v_monthly, status = v_status,
      terms_status = v_terms, payment_method = v_method, payment_due_date = v_due,
      payment_terms_note = v_terms_note, recurring_plan_id = v_recurring,
      reserve_plan_id = v_reserve, memo = v_memo, updated_at = now()
    where id = p_contract_id;
    v_id := p_contract_id;
  end if;

  select to_jsonb(c) into v_after from public.ledger_rent_contracts c where c.id = v_id;
  insert into public.ledger_audit_logs(actor_user_id, action, entity_type, entity_id, before_snapshot, after_snapshot, reason)
  values (p_actor_user_id, case when p_contract_id is null then 'rent_contract_created' else 'rent_contract_updated' end,
    'rent_contract', v_id, case when p_contract_id is null then null else to_jsonb(v_before) end, v_after, null);

  return jsonb_build_object('status', 'saved', 'contractId', v_id);
end
$$;

-- Link an existing confirmed prepaid_expense_payment to a contract. The ledger row is
-- only read. p_replaces_payment_id converts a pre_ledger row of the same contract and
-- amount into this ledger link (for a future full July migration), so the payment is
-- never counted twice.
create function public.ledger_link_rent_payment_v1(
  p_contract_id bigint,
  p_payment_transaction_id bigint,
  p_replaces_payment_id bigint,
  p_memo text,
  p_actor_user_id bigint
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_contract public.ledger_rent_contracts%rowtype;
  v_tx public.ledger_transactions%rowtype;
  v_replaced public.ledger_rent_contract_payments%rowtype;
  v_outflow numeric;
  v_account bigint;
  v_paid numeric;
  v_id bigint;
begin
  if not public.ledger_rent_actor_can_write_v1(p_actor_user_id) then
    return jsonb_build_object('status', 'forbidden');
  end if;
  select * into v_contract from public.ledger_rent_contracts where id = p_contract_id for update;
  if v_contract.id is null then
    return jsonb_build_object('status', 'contract_not_found');
  end if;
  perform pg_advisory_xact_lock(hashtext('ledger_rent_payment_tx:' || coalesce(p_payment_transaction_id, 0)::text));

  select * into v_tx from public.ledger_transactions where id = p_payment_transaction_id;
  if v_tx.id is null then
    return jsonb_build_object('status', 'transaction_not_found');
  end if;
  if v_tx.type <> 'prepaid_expense_payment' or v_tx.status <> 'confirmed' then
    return jsonb_build_object('status', 'invalid_transaction');
  end if;
  -- Must be real money out of a business fund (not a recognition or a draft).
  select -sum(m.amount), min(m.fund_account_id) into v_outflow, v_account
  from public.ledger_movements m
  join public.ledger_fund_accounts f on f.id = m.fund_account_id and f.is_business_fund = true
  where m.transaction_id = v_tx.id and m.amount < 0;
  if v_outflow is null or v_outflow <> v_tx.amount then
    return jsonb_build_object('status', 'invalid_transaction');
  end if;
  if exists (select 1 from public.ledger_rent_contract_payments where payment_transaction_id = v_tx.id) then
    return jsonb_build_object('status', 'already_linked');
  end if;

  if p_replaces_payment_id is not null then
    select * into v_replaced from public.ledger_rent_contract_payments
    where id = p_replaces_payment_id for update;
    if v_replaced.id is null or v_replaced.contract_id <> v_contract.id
      or v_replaced.source <> 'pre_ledger' or v_replaced.amount <> v_tx.amount then
      return jsonb_build_object('status', 'invalid_replacement');
    end if;
    update public.ledger_rent_contract_payments set
      source = 'ledger', payment_transaction_id = v_tx.id, paid_on = v_tx.business_date,
      fund_account_id = v_account, updated_at = now()
    where id = v_replaced.id;
    insert into public.ledger_audit_logs(actor_user_id, action, entity_type, entity_id, before_snapshot, after_snapshot, reason)
    values (p_actor_user_id, 'rent_payment_converted_to_ledger', 'rent_contract_payment', v_replaced.id,
      to_jsonb(v_replaced), (select to_jsonb(p) from public.ledger_rent_contract_payments p where p.id = v_replaced.id),
      nullif(btrim(p_memo), ''));
    return jsonb_build_object('status', 'converted', 'paymentId', v_replaced.id);
  end if;

  select coalesce(sum(amount), 0) into v_paid from public.ledger_rent_contract_payments where contract_id = v_contract.id;
  if v_paid + v_tx.amount > v_contract.annual_amount then
    return jsonb_build_object('status', 'exceeds_contract_amount', 'paidAmount', v_paid, 'contractAmount', v_contract.annual_amount);
  end if;

  insert into public.ledger_rent_contract_payments(
    contract_id, source, payment_transaction_id, paid_on, amount, fund_account_id, memo, created_by
  ) values (
    v_contract.id, 'ledger', v_tx.id, v_tx.business_date, v_tx.amount, v_account, nullif(btrim(p_memo), ''), p_actor_user_id
  ) returning id into v_id;
  insert into public.ledger_audit_logs(actor_user_id, action, entity_type, entity_id, before_snapshot, after_snapshot, reason)
  values (p_actor_user_id, 'rent_payment_linked', 'rent_contract_payment', v_id, null,
    (select to_jsonb(p) from public.ledger_rent_contract_payments p where p.id = v_id), nullif(btrim(p_memo), ''));
  return jsonb_build_object('status', 'linked', 'paymentId', v_id);
exception when unique_violation then
  return jsonb_build_object('status', 'already_linked');
end
$$;

-- Record evidence of a payment made before the app ledger opened. No transaction,
-- no movement: its cash is already inside the opening balance seed.
create function public.ledger_record_pre_ledger_rent_payment_v1(
  p_contract_id bigint,
  p_reference text,
  p_paid_on date,
  p_amount numeric,
  p_fund_account_id bigint,
  p_memo text,
  p_actor_user_id bigint
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_contract public.ledger_rent_contracts%rowtype;
  v_start date;
  v_paid numeric;
  v_id bigint;
begin
  if not public.ledger_rent_actor_can_write_v1(p_actor_user_id) then
    return jsonb_build_object('status', 'forbidden');
  end if;
  if nullif(btrim(p_reference), '') is null or p_paid_on is null or p_amount is null
    or p_amount <= 0 or scale(p_amount) > 3 then
    return jsonb_build_object('status', 'invalid_payload');
  end if;
  select * into v_contract from public.ledger_rent_contracts where id = p_contract_id for update;
  if v_contract.id is null then
    return jsonb_build_object('status', 'contract_not_found');
  end if;
  v_start := public.ledger_rent_ledger_start_v1();
  if v_start is null then
    return jsonb_build_object('status', 'ledger_start_unknown');
  end if;
  if p_paid_on >= v_start then
    -- Anything on/after the ledger start must be an actual ledger transaction.
    return jsonb_build_object('status', 'not_pre_ledger', 'ledgerStart', v_start);
  end if;
  if p_fund_account_id is not null and not exists (select 1 from public.ledger_fund_accounts where id = p_fund_account_id) then
    return jsonb_build_object('status', 'invalid_fund_account');
  end if;
  if exists (select 1 from public.ledger_rent_contract_payments where pre_ledger_reference = btrim(p_reference)) then
    return jsonb_build_object('status', 'already_recorded');
  end if;
  select coalesce(sum(amount), 0) into v_paid from public.ledger_rent_contract_payments where contract_id = v_contract.id;
  if v_paid + p_amount > v_contract.annual_amount then
    return jsonb_build_object('status', 'exceeds_contract_amount', 'paidAmount', v_paid, 'contractAmount', v_contract.annual_amount);
  end if;

  insert into public.ledger_rent_contract_payments(
    contract_id, source, pre_ledger_reference, paid_on, amount, fund_account_id, memo, created_by
  ) values (
    v_contract.id, 'pre_ledger', btrim(p_reference), p_paid_on, p_amount, p_fund_account_id, nullif(btrim(p_memo), ''), p_actor_user_id
  ) returning id into v_id;
  insert into public.ledger_audit_logs(actor_user_id, action, entity_type, entity_id, before_snapshot, after_snapshot, reason)
  values (p_actor_user_id, 'rent_payment_pre_ledger_recorded', 'rent_contract_payment', v_id, null,
    (select to_jsonb(p) from public.ledger_rent_contract_payments p where p.id = v_id), nullif(btrim(p_memo), ''));
  return jsonb_build_object('status', 'recorded', 'paymentId', v_id);
exception when unique_violation then
  return jsonb_build_object('status', 'already_recorded');
end
$$;

