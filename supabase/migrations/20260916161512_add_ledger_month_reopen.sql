-- Preserve each prior close while allowing the same month row to be reopened and closed again.
-- No operational rows are changed by this migration.
alter table public.ledger_month_closures drop constraint ledger_month_closures_status_check;
alter table public.ledger_month_closures add constraint ledger_month_closures_status_check
  check (status in ('closed', 'reopened'));
alter table public.ledger_month_closures
  add column reopened_at timestamptz,
  add column reopened_by bigint references public.users(id) on delete restrict,
  add column reopen_reason text,
  add column revision integer not null default 1;
alter table public.ledger_month_closures add constraint ledger_month_closures_revision_check check (revision >= 1);

create table public.ledger_month_closure_history (
  id bigint generated by default as identity primary key,
  closure_id bigint not null references public.ledger_month_closures(id) on delete restrict,
  month date not null check (month = date_trunc('month', month)::date),
  revision integer not null check (revision >= 1),
  closed_at timestamptz not null,
  closed_by bigint not null references public.users(id) on delete restrict,
  preflight_snapshot jsonb not null check (jsonb_typeof(preflight_snapshot) = 'object'),
  summary_snapshot jsonb not null check (jsonb_typeof(summary_snapshot) = 'object'),
  snapshot_hash text not null check (snapshot_hash ~ '^[0-9a-f]{64}$'),
  warning_snapshot jsonb not null check (jsonb_typeof(warning_snapshot) = 'array'),
  archived_reason text not null check (btrim(archived_reason) <> ''),
  archived_at timestamptz not null default now(),
  archived_by bigint not null references public.users(id) on delete restrict,
  unique (closure_id, revision)
);
alter table public.ledger_month_closure_history owner to postgres;
alter sequence public.ledger_month_closure_history_id_seq owner to postgres;
alter table public.ledger_month_closure_history enable row level security;
