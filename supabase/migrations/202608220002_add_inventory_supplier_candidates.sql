create table public.business_partner_supplier_aliases (
  id bigint generated by default as identity primary key,
  supplier_name text not null check (length(btrim(supplier_name)) between 1 and 200),
  normalized_name text not null check (length(normalized_name) between 1 and 200),
  status text not null default 'pending' check (status in ('pending', 'linked', 'ignored')),
  business_partner_id bigint null references public.business_partners(id) on delete restrict,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  reviewed_at timestamptz null,
  reviewed_by bigint null references public.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint business_partner_supplier_alias_status_policy check (
    (status = 'linked' and business_partner_id is not null and reviewed_at is not null and reviewed_by is not null)
    or (status = 'ignored' and business_partner_id is null and reviewed_at is not null and reviewed_by is not null)
    or (status = 'pending' and business_partner_id is null and reviewed_at is null and reviewed_by is null)
  )
);

create unique index business_partner_supplier_aliases_normalized_unique
  on public.business_partner_supplier_aliases (normalized_name);
create index business_partner_supplier_aliases_review_idx
  on public.business_partner_supplier_aliases (status, last_seen_at desc, id desc);
create index business_partner_supplier_aliases_partner_idx
  on public.business_partner_supplier_aliases (business_partner_id)
  where business_partner_id is not null;

alter table public.inventory
  add column supplier_partner_id bigint null
  references public.business_partners(id) on delete restrict;
create index inventory_supplier_partner_id_idx
  on public.inventory (supplier_partner_id, is_active, id);
create index inventory_supplier_normalized_idx
  on public.inventory (lower(btrim(supplier)))
  where supplier is not null and btrim(supplier) <> '';

create table public.business_partner_supplier_alias_audit_logs (
  id bigint generated by default as identity primary key,
  supplier_alias_id bigint not null references public.business_partner_supplier_aliases(id) on delete restrict,
  actor_user_id bigint not null references public.users(id) on delete restrict,
  action text not null check (action in ('candidate_created','candidate_linked_new_partner','candidate_linked_existing_partner','candidate_ignored','candidate_reopened')),
  before_snapshot jsonb null check (before_snapshot is null or jsonb_typeof(before_snapshot) = 'object'),
  after_snapshot jsonb null check (after_snapshot is null or jsonb_typeof(after_snapshot) = 'object'),
  created_at timestamptz not null default now()
);
create index business_partner_supplier_alias_audit_alias_idx
  on public.business_partner_supplier_alias_audit_logs (supplier_alias_id, created_at desc, id desc);

insert into public.business_partner_supplier_aliases(supplier_name, normalized_name)
select min(btrim(i.supplier)), lower(btrim(i.supplier))
from public.inventory i
where i.supplier is not null and btrim(i.supplier) <> ''
group by lower(btrim(i.supplier))
on conflict(normalized_name) do nothing;

alter table public.business_partner_supplier_aliases enable row level security;
alter table public.business_partner_supplier_alias_audit_logs enable row level security;

revoke all on table public.business_partner_supplier_aliases, public.business_partner_supplier_alias_audit_logs
