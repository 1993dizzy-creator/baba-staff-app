create table public.business_partners (
  id bigint generated by default as identity primary key,
  name text not null check (length(btrim(name)) between 1 and 200),
  partner_type text not null default 'other' check (length(btrim(partner_type)) between 1 and 80),
  payment_mode text not null check (payment_mode in ('immediate','postpaid')),
  default_payment_term_days integer null,
  phone text null check (phone is null or length(btrim(phone)) <= 80),
  contact_name text null check (contact_name is null or length(btrim(contact_name)) <= 120),
  memo text null check (memo is null or length(memo) <= 5000),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint business_partners_payment_term_policy check (
    (payment_mode = 'immediate' and default_payment_term_days is null)
    or
    (payment_mode = 'postpaid' and default_payment_term_days between 0 and 3650)
  )
);

create unique index business_partners_name_unique
  on public.business_partners (lower(btrim(name)));
create index business_partners_active_mode_idx
  on public.business_partners (is_active, payment_mode, id desc);
create index business_partners_type_idx
  on public.business_partners (partner_type, is_active, id desc);

create table public.business_partner_ledger_parties (
  business_partner_id bigint primary key references public.business_partners(id) on delete restrict,
  ledger_party_id bigint not null unique references public.ledger_parties(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index business_partner_ledger_parties_ledger_idx
  on public.business_partner_ledger_parties (ledger_party_id);

create table public.business_partner_audit_logs (
  id bigint generated by default as identity primary key,
  business_partner_id bigint not null references public.business_partners(id) on delete restrict,
  actor_user_id bigint not null references public.users(id) on delete restrict,
  action text not null check (action in ('created','updated','ledger_party_linked','ledger_party_unlinked')),
  before_snapshot jsonb null check (before_snapshot is null or jsonb_typeof(before_snapshot) = 'object'),
  after_snapshot jsonb null check (after_snapshot is null or jsonb_typeof(after_snapshot) = 'object'),
  created_at timestamptz not null default now()
);

create index business_partner_audit_logs_partner_idx
  on public.business_partner_audit_logs (business_partner_id, created_at desc, id desc);
create index business_partner_audit_logs_actor_idx
  on public.business_partner_audit_logs (actor_user_id, created_at desc);

alter table public.business_partners enable row level security;
alter table public.business_partner_ledger_parties enable row level security;
alter table public.business_partner_audit_logs enable row level security;

revoke all on table public.business_partners, public.business_partner_ledger_parties, public.business_partner_audit_logs
  from public, anon, authenticated, service_role;
revoke all on sequence public.business_partners_id_seq, public.business_partner_audit_logs_id_seq
  from public, anon, authenticated, service_role;

grant select on table public.business_partners, public.business_partner_ledger_parties, public.business_partner_audit_logs to service_role;

create function public.business_partner_create_v1(
  p_name text,
  p_partner_type text,
  p_payment_mode text,
  p_default_payment_term_days integer,
  p_phone text,
  p_contact_name text,
  p_memo text,
  p_is_active boolean,
  p_ledger_party_id bigint,
  p_actor_user_id bigint
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_role text;
  v_id bigint;
begin
  select lower(role::text) into v_role
  from public.users
  where id = p_actor_user_id and is_active = true and app_login_enabled = true;
  if coalesce(v_role, '') not in ('owner', 'master') then
    return jsonb_build_object('status', 'forbidden');
  end if;

  if p_ledger_party_id is not null and not exists (
    select 1 from public.ledger_parties where id = p_ledger_party_id and is_active = true
  ) then
    return jsonb_build_object('status', 'invalid_ledger_party');
  end if;
  if p_ledger_party_id is not null and exists (
    select 1 from public.business_partner_ledger_parties where ledger_party_id = p_ledger_party_id
  ) then
    return jsonb_build_object('status', 'ledger_party_already_linked');
  end if;

  insert into public.business_partners(
    name, partner_type, payment_mode, default_payment_term_days,
    phone, contact_name, memo, is_active
  ) values (
    btrim(p_name), btrim(p_partner_type), p_payment_mode, p_default_payment_term_days,
    nullif(btrim(p_phone), ''), nullif(btrim(p_contact_name), ''), nullif(btrim(p_memo), ''), p_is_active
  ) returning id into v_id;

  if p_ledger_party_id is not null then
    insert into public.business_partner_ledger_parties(business_partner_id, ledger_party_id)
    values(v_id, p_ledger_party_id);
  end if;

  insert into public.business_partner_audit_logs(
    business_partner_id, actor_user_id, action, after_snapshot
  ) values (
    v_id, p_actor_user_id, 'created',
    (select to_jsonb(p) from public.business_partners p where p.id = v_id)
  );
  return jsonb_build_object('status', 'created', 'partnerId', v_id);
exception
  when unique_violation then return jsonb_build_object('status', 'duplicate_name');
  when check_violation or foreign_key_violation or not_null_violation then return jsonb_build_object('status', 'invalid_input');
end;
$$;

create function public.business_partner_update_v1(
  p_partner_id bigint,
  p_name text,
  p_partner_type text,
  p_payment_mode text,
  p_default_payment_term_days integer,
  p_phone text,
  p_contact_name text,
  p_memo text,
  p_is_active boolean,
  p_ledger_party_id bigint,
  p_actor_user_id bigint
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_role text;
  v_before jsonb;
  v_previous_ledger_party_id bigint;
begin
  select lower(role::text) into v_role
  from public.users
  where id = p_actor_user_id and is_active = true and app_login_enabled = true;
  if coalesce(v_role, '') not in ('owner', 'master') then
    return jsonb_build_object('status', 'forbidden');
  end if;

  select to_jsonb(p) into v_before
  from public.business_partners p where p.id = p_partner_id for update;
  if v_before is null then return jsonb_build_object('status', 'not_found'); end if;

  if p_ledger_party_id is not null and not exists (
    select 1 from public.ledger_parties where id = p_ledger_party_id and is_active = true
  ) then
    return jsonb_build_object('status', 'invalid_ledger_party');
  end if;
  if p_ledger_party_id is not null and exists (
    select 1 from public.business_partner_ledger_parties
    where ledger_party_id = p_ledger_party_id and business_partner_id <> p_partner_id
  ) then
    return jsonb_build_object('status', 'ledger_party_already_linked');
  end if;

  select ledger_party_id into v_previous_ledger_party_id
  from public.business_partner_ledger_parties where business_partner_id = p_partner_id;

  update public.business_partners set
    name = btrim(p_name),
    partner_type = btrim(p_partner_type),
    payment_mode = p_payment_mode,
    default_payment_term_days = p_default_payment_term_days,
    phone = nullif(btrim(p_phone), ''),
    contact_name = nullif(btrim(p_contact_name), ''),
    memo = nullif(btrim(p_memo), ''),
    is_active = p_is_active,
    updated_at = now()
  where id = p_partner_id;

  if p_ledger_party_id is null then
    delete from public.business_partner_ledger_parties where business_partner_id = p_partner_id;
  else
    insert into public.business_partner_ledger_parties(business_partner_id, ledger_party_id, updated_at)
    values(p_partner_id, p_ledger_party_id, now())
    on conflict(business_partner_id) do update
      set ledger_party_id = excluded.ledger_party_id, updated_at = now();
  end if;

  insert into public.business_partner_audit_logs(
    business_partner_id, actor_user_id, action, before_snapshot, after_snapshot
  ) values (
    p_partner_id, p_actor_user_id, 'updated', v_before,
    (select to_jsonb(p) from public.business_partners p where p.id = p_partner_id)
  );
  if v_previous_ledger_party_id is distinct from p_ledger_party_id then
    insert into public.business_partner_audit_logs(
      business_partner_id, actor_user_id, action, before_snapshot, after_snapshot
    ) values (
      p_partner_id, p_actor_user_id,
      case when p_ledger_party_id is null then 'ledger_party_unlinked' else 'ledger_party_linked' end,
      case when v_previous_ledger_party_id is null then null else jsonb_build_object('ledgerPartyId', v_previous_ledger_party_id) end,
      case when p_ledger_party_id is null then null else jsonb_build_object('ledgerPartyId', p_ledger_party_id) end
    );
  end if;
  return jsonb_build_object('status', 'updated', 'partnerId', p_partner_id);
exception
  when unique_violation then return jsonb_build_object('status', 'duplicate_name');
  when check_violation or foreign_key_violation or not_null_violation then return jsonb_build_object('status', 'invalid_input');
end;
$$;

