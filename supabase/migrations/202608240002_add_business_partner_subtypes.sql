-- Subtype management (create/update/deactivate). No physical delete: a subtype already
-- referenced by a Partner is deactivated instead, and stays correctly displayable there.
create function public.business_partner_subtype_create_v1(
  p_partner_type text,
  p_name_ko text,
  p_name_vi text,
  p_sort_order integer,
  p_actor_user_id bigint
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_role text;
  v_id bigint;
begin
  select lower(role::text) into v_role
  from public.users
  where id = p_actor_user_id and is_active = true and app_login_enabled = true;
  if coalesce(v_role, '') not in ('owner', 'master') then
    return jsonb_build_object('status', 'forbidden');
  end if;

  if nullif(btrim(p_name_ko), '') is null and nullif(btrim(p_name_vi), '') is null then
    return jsonb_build_object('status', 'invalid_name');
  end if;

  -- Server-generated stable code (custom_<id>): the management UI never lets an operator
  -- type a code directly, and KO/VI display names are never relied on as an identity.
  v_id := nextval('public.business_partner_subtypes_id_seq');
  insert into public.business_partner_subtypes(id, code, partner_type, name_ko, name_vi, sort_order, is_active)
  values (v_id, 'custom_' || v_id, btrim(p_partner_type), nullif(btrim(p_name_ko), ''), nullif(btrim(p_name_vi), ''), coalesce(p_sort_order, 0), true);

  return jsonb_build_object('status', 'created', 'subtypeId', v_id, 'code', 'custom_' || v_id);
exception
  when check_violation or not_null_violation then return jsonb_build_object('status', 'invalid_input');
end;
$$;

create function public.business_partner_subtype_update_v1(
  p_subtype_id bigint,
  p_name_ko text,
  p_name_vi text,
  p_sort_order integer,
  p_is_active boolean,
  p_actor_user_id bigint
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_role text;
  v_before jsonb;
begin
  select lower(role::text) into v_role
  from public.users
  where id = p_actor_user_id and is_active = true and app_login_enabled = true;
  if coalesce(v_role, '') not in ('owner', 'master') then
    return jsonb_build_object('status', 'forbidden');
  end if;

  select to_jsonb(s) into v_before
  from public.business_partner_subtypes s where s.id = p_subtype_id for update;
  if v_before is null then return jsonb_build_object('status', 'not_found'); end if;

  if nullif(btrim(p_name_ko), '') is null and nullif(btrim(p_name_vi), '') is null then
    return jsonb_build_object('status', 'invalid_name');
  end if;

  -- partner_type and code are immutable here: changing partner_type could silently
  -- orphan every Partner already pointed at this subtype (section 3's category
  -- integrity), and code is a stable identifier independent of display names.
  update public.business_partner_subtypes set
    name_ko = nullif(btrim(p_name_ko), ''),
    name_vi = nullif(btrim(p_name_vi), ''),
    sort_order = coalesce(p_sort_order, sort_order),
    is_active = p_is_active,
    updated_at = now()
  where id = p_subtype_id;

  return jsonb_build_object('status', 'updated', 'subtypeId', p_subtype_id);
exception
  when check_violation or not_null_violation then return jsonb_build_object('status', 'invalid_input');
end;
$$;

