-- Partner "중분류" (subtype): a multilingual reference-master classification nested under
-- partner_type, kept as its own table (not free text on business_partners) so it can later
-- narrow Partner comparison/recommendation (partner_type -> subtype -> inventory overlap ->
-- price/spec). NOT a replacement for inventory.category, and NOT the same thing as
-- display_tag (a free single user memo badge) -- both keep their existing separate roles.
--
-- 1. business_partner_subtypes table
-- 2. constraints/indexes
-- 3. initial subtype seed (reference-master data only, no business_partners row touched)
-- 4. business_partners.partner_subtype_id nullable FK
-- 5. eligibility helper + V4 create/update/review RPCs + subtype management RPCs

create table public.business_partner_subtypes (
  id bigint generated by default as identity primary key,
  code text not null check (length(btrim(code)) between 1 and 80),
  partner_type text not null check (length(btrim(partner_type)) between 1 and 80),
  name_ko text null check (name_ko is null or length(btrim(name_ko)) <= 80),
  name_vi text null check (name_vi is null or length(btrim(name_vi)) <= 80),
  sort_order integer not null default 0 check (sort_order between 0 and 100000),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint business_partner_subtypes_name_present check (
    nullif(btrim(name_ko), '') is not null
    or
    nullif(btrim(name_vi), '') is not null
  )
);

create unique index business_partner_subtypes_code_unique
  on public.business_partner_subtypes (lower(btrim(code)));
create index business_partner_subtypes_type_idx
  on public.business_partner_subtypes (partner_type, is_active, sort_order);

