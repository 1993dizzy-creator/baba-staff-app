-- Eligibility helper, mirroring business_partner_fund_account_is_eligible_v1's shape:
-- NULL is always eligible (unclassified). A non-NULL id must belong to p_partner_type.
-- It must also be is_active=true UNLESS it equals p_current_subtype_id, which lets an
-- update keep a Partner's already-assigned subtype even after that subtype is later
-- deactivated (info screens keep showing it correctly; only *new* assignment requires
-- an active subtype). Create/review-alias call sites omit p_current_subtype_id (NULL
-- default), so a brand-new Partner can only ever be assigned an active subtype.
create function public.business_partner_subtype_is_eligible_v1(
  p_partner_subtype_id bigint,
  p_partner_type text,
  p_current_subtype_id bigint default null
) returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select p_partner_subtype_id is null or exists (
    select 1 from public.business_partner_subtypes
    where id = p_partner_subtype_id
      and partner_type = p_partner_type
      and (is_active = true or id = p_current_subtype_id)
  );
$$;

