-- 직원 식대 대상 관리 + 식대 현재·예상비용 1차 기능.
--
-- 식대는 출근 당일 현금으로 지급되며(실제 지급 여부는 이번 단계에서 관리하지 않음), 월 급여
-- 지급액·직원 실수령액에는 포함하지 않는다. 그래서 이 Migration은:
--   1) 공통 1일 식대 금액을 effective-dated version 테이블로 관리한다
--      (payroll_settings 단일 행에 컬럼을 추가하지 않는다 — 월 중간 금액 변경 시 과거
--      재현이 불가능해지기 때문).
--   2) 직원별 식대 대상 여부를 급여계약과 분리된 effective-dated version 테이블로 관리한다
--      (계약은 "이미 급여 계산/지급에 사용되면 잠기는" 정책이 있어 식대 온/오프처럼 지급액과
--      무관한 변경까지 막아버리기 때문. 두 테이블 모두 payroll_insurance_setting_versions와
--      동일한 append-only 패턴 — 별도 audit 테이블 없이 version 자체가 이력이다).
--   3) 근태 기록 미사용 직원(attendance_tracking_enabled=false)은 식대 대상으로 설정할 수
--      없게 RPC에서 차단하고, 반대로 이미 식대 대상인 직원의 근태 사용을 끄는 시도도
--      trigger로 차단해 "식대 대상만 남고 근태 미사용"이라는 모순 상태를 막는다.
--
-- 기존 payroll_contract_versions·payroll_insurance_setting_versions·payroll_run_*·
-- payroll_pay_employee_v1 등은 전혀 수정하지 않는다. 새 테이블·새 RPC만 추가한다.

begin;

