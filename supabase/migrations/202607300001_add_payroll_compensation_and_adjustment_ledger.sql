alter table public.payroll_runs
  add column force_finalized boolean not null default false,
  add column finalized_actor_role text null,
  add column force_finalize_reason text null,
  add column force_finalize_snapshot jsonb null,
  add constraint payroll_run_finalized_actor_role check (finalized_actor_role is null or finalized_actor_role in ('owner','master')),
  add constraint payroll_run_force_finalize_audit check (
    (force_finalized = false and force_finalize_reason is null and force_finalize_snapshot is null)
    or (
      force_finalized = true
      and finalized_by is not null
      and finalized_at is not null
      and finalized_actor_role in ('owner','master')
      and length(btrim(force_finalize_reason)) > 0
      and jsonb_typeof(force_finalize_snapshot) = 'object'
    )
  );

create table public.payroll_monthly_adjustments (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete restrict,
  payroll_month date not null check (payroll_month = date_trunc('month', payroll_month)::date),
  kind text not null check (kind in ('incentive', 'penalty')),
  category text not null check (category in ('sales','performance','service','late','early_leave','absence','damage','discipline','manual','other')),
  amount numeric(16,0) not null check (amount >= 1 and amount = trunc(amount)),
  business_date date not null,
  reason text not null check (length(btrim(reason)) > 0),
  note text null,
  source_type text not null default 'manual' check (source_type = 'manual'),
  source_key text null,
  created_by bigint not null references public.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  cancelled_at timestamptz null,
  cancelled_by bigint null references public.users(id) on delete restrict,
  cancellation_reason text null,
  constraint payroll_adjustment_business_month check (date_trunc('month', business_date)::date = payroll_month),
  constraint payroll_adjustment_cancel_audit check (
    (cancelled_at is null and cancelled_by is null and cancellation_reason is null)
    or (cancelled_at is not null and cancelled_by is not null and length(btrim(cancellation_reason)) > 0)
  )
);

create index payroll_monthly_adjustments_month_user_idx
  on public.payroll_monthly_adjustments(payroll_month, user_id, created_at desc);
create unique index payroll_monthly_adjustments_source_unique
  on public.payroll_monthly_adjustments(source_type, source_key)
  where source_key is not null;

