create function public.payroll_validate_tax_brackets_v1(p_brackets jsonb)
returns boolean
language plpgsql
immutable
set search_path=pg_catalog, public
as $$
declare
  v_index integer;
  v_count integer;
  v_bracket jsonb;
  v_lower numeric;
  v_upper numeric;
  v_rate numeric;
  v_expected_lower numeric := 0;
begin
  if jsonb_typeof(p_brackets) <> 'array' then return false; end if;
  v_count := jsonb_array_length(p_brackets);
  if v_count < 1 then return false; end if;
  for v_index in 0..v_count-1 loop
    v_bracket := p_brackets -> v_index;
    if jsonb_typeof(v_bracket) <> 'object'
      or jsonb_typeof(v_bracket -> 'lowerBoundAmount') <> 'number'
      or jsonb_typeof(v_bracket -> 'rateBp') <> 'number' then return false; end if;
    v_lower := (v_bracket ->> 'lowerBoundAmount')::numeric;
    v_rate := (v_bracket ->> 'rateBp')::numeric;
    if v_lower <> trunc(v_lower) or v_lower < 0 or v_lower > 9007199254740991 or v_lower <> v_expected_lower
      or v_rate <> trunc(v_rate) or v_rate < 0 or v_rate >= 10000 then return false; end if;
    if v_index = v_count - 1 then
      if (v_bracket -> 'upperBoundAmount') is distinct from 'null'::jsonb then return false; end if;
    else
      if jsonb_typeof(v_bracket -> 'upperBoundAmount') <> 'number' then return false; end if;
      v_upper := (v_bracket ->> 'upperBoundAmount')::numeric;
      if v_upper <> trunc(v_upper) or v_upper > 9007199254740991 or v_upper <= v_lower then return false; end if;
      v_expected_lower := v_upper;
    end if;
  end loop;
  return true;
exception when others then
  return false;
end $$;

create table public.payroll_tax_policy_versions (
  id bigint generated by default as identity primary key,
  effective_month date not null,
  personal_deduction_amount numeric(16,0) not null,
  dependent_deduction_amount numeric(16,0) not null,
  brackets jsonb not null,
  revision bigint not null,
  created_by bigint not null references public.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  note text null,
  constraint payroll_tax_policy_month_check check (effective_month = date_trunc('month', effective_month)::date),
  constraint payroll_tax_policy_personal_deduction_check check (personal_deduction_amount between 0 and 9007199254740991 and personal_deduction_amount = trunc(personal_deduction_amount)),
  constraint payroll_tax_policy_dependent_deduction_check check (dependent_deduction_amount between 0 and 9007199254740991 and dependent_deduction_amount = trunc(dependent_deduction_amount)),
  constraint payroll_tax_policy_brackets_check check (public.payroll_validate_tax_brackets_v1(brackets)),
  constraint payroll_tax_policy_revision_check check (revision >= 1),
  constraint payroll_tax_policy_revision_unique unique (revision)
);

create index payroll_tax_policy_lookup_idx
  on public.payroll_tax_policy_versions(effective_month desc, revision desc);

create table public.payroll_tax_setting_versions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete restrict,
  effective_month date not null,
  tax_mode text not null,
  dependent_count integer not null,
  burden_mode text not null,
  accounting_name text null,
  insurance_deduction_mode text not null,
  manual_insurance_deduction_amount numeric(16,0) not null default 0,
  revision bigint not null,
  created_by bigint not null references public.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  note text null,
  constraint payroll_tax_setting_month_check check (effective_month = date_trunc('month', effective_month)::date),
  constraint payroll_tax_setting_mode_check check (tax_mode in ('not_applicable', 'resident_progressive')),
  constraint payroll_tax_setting_dependent_count_check check (dependent_count between 0 and 1000),
  constraint payroll_tax_setting_burden_mode_check check (burden_mode in ('employee_deducted', 'company_bears')),
  constraint payroll_tax_setting_insurance_mode_check check (insurance_deduction_mode in ('payroll', 'manual', 'none')),
  constraint payroll_tax_setting_manual_insurance_check check (
    manual_insurance_deduction_amount between 0 and 9007199254740991
    and manual_insurance_deduction_amount = trunc(manual_insurance_deduction_amount)
    and ((insurance_deduction_mode = 'manual') or manual_insurance_deduction_amount = 0)
  ),
  constraint payroll_tax_setting_manual_note_check check (insurance_deduction_mode <> 'manual' or nullif(btrim(note), '') is not null),
  constraint payroll_tax_setting_not_applicable_shape_check check (
    tax_mode <> 'not_applicable'
    or (dependent_count = 0 and burden_mode = 'employee_deducted' and insurance_deduction_mode = 'none' and manual_insurance_deduction_amount = 0)
  ),
  constraint payroll_tax_setting_revision_check check (revision >= 1),
  constraint payroll_tax_setting_version_unique unique (user_id, revision)
);

create index payroll_tax_setting_lookup_idx
  on public.payroll_tax_setting_versions(user_id, effective_month desc, revision desc);
create index payroll_tax_setting_created_by_idx
  on public.payroll_tax_setting_versions(created_by);

