create function public.payroll_lock_paid_tax_policy_v1()
returns trigger
language plpgsql
security definer
set search_path=pg_catalog, public
as $$
begin
  perform pg_advisory_xact_lock(82120, extract(year from new.effective_month)::integer * 100 + extract(month from new.effective_month)::integer);
  if exists (
    select 1
    from public.payroll_payment_batches b
    join public.payroll_employee_payments e on e.payroll_batch_id = b.id
    where b.payroll_month >= new.effective_month and e.payment_status = 'paid'
  ) then
    raise exception 'PAYROLL_TAX_POLICY_LOCKED_FOR_PAID_MONTH' using errcode = '55000';
  end if;
  return new;
end $$;

create function public.payroll_lock_paid_tax_setting_v1()
returns trigger
language plpgsql
security definer
set search_path=pg_catalog, public
as $$
begin
  perform pg_advisory_xact_lock(82119, new.user_id::integer);
  if exists (
    select 1
    from public.payroll_payment_batches b
    join public.payroll_employee_payments e on e.payroll_batch_id = b.id
    where b.payroll_month >= new.effective_month
      and e.user_id = new.user_id
      and e.payment_status = 'paid'
  ) then
    raise exception 'PAYROLL_TAX_SETTING_LOCKED_FOR_PAID_EMPLOYEE' using errcode = '55000';
  end if;
  return new;
end $$;

create trigger payroll_tax_policy_paid_lock
before insert or update on public.payroll_tax_policy_versions
for each row execute function public.payroll_lock_paid_tax_policy_v1();

create trigger payroll_tax_setting_paid_lock
before insert or update on public.payroll_tax_setting_versions
for each row execute function public.payroll_lock_paid_tax_setting_v1();

create function public.payroll_create_tax_policy_version_v1(
  p_effective_month date,
  p_personal_deduction_amount bigint,
  p_dependent_deduction_amount bigint,
  p_brackets jsonb,
  p_actor_user_id bigint,
  p_note text
) returns jsonb
language plpgsql
security definer
set search_path=pg_catalog, public
as $$
declare
  v_revision bigint;
  v_created public.payroll_tax_policy_versions%rowtype;
begin
  perform public.payroll_assert_actor_v2(p_actor_user_id);
  if p_effective_month <> date_trunc('month', p_effective_month)::date
    or p_personal_deduction_amount < 0
    or p_dependent_deduction_amount < 0
    or not public.payroll_validate_tax_brackets_v1(p_brackets) then
    raise exception 'PAYROLL_TAX_POLICY_INVALID' using errcode = '22023';
  end if;
  perform pg_advisory_xact_lock(82120, 1);
  select coalesce(max(revision), 0) + 1 into v_revision from public.payroll_tax_policy_versions;
  insert into public.payroll_tax_policy_versions(
    effective_month, personal_deduction_amount, dependent_deduction_amount,
    brackets, revision, created_by, note
  ) values (
    p_effective_month, p_personal_deduction_amount, p_dependent_deduction_amount,
    p_brackets, v_revision, p_actor_user_id, nullif(btrim(p_note), '')
  ) returning * into v_created;
  return to_jsonb(v_created);
end $$;

create function public.payroll_create_tax_setting_version_v1(
  p_user_id bigint,
  p_effective_month date,
  p_tax_mode text,
  p_dependent_count integer,
  p_burden_mode text,
  p_accounting_name text,
  p_insurance_deduction_mode text,
  p_manual_insurance_deduction_amount bigint,
  p_actor_user_id bigint,
  p_note text
) returns jsonb
language plpgsql
security definer
set search_path=pg_catalog, public
as $$
declare
  v_revision bigint;
  v_created public.payroll_tax_setting_versions%rowtype;
begin
  perform public.payroll_assert_actor_v2(p_actor_user_id);
  if p_effective_month <> date_trunc('month', p_effective_month)::date
    or p_tax_mode not in ('not_applicable', 'resident_progressive')
    or p_dependent_count not between 0 and 1000
    or p_burden_mode not in ('employee_deducted', 'company_bears')
    or p_insurance_deduction_mode not in ('payroll', 'manual', 'none')
    or p_manual_insurance_deduction_amount < 0
    or (p_insurance_deduction_mode <> 'manual' and p_manual_insurance_deduction_amount <> 0)
    or (p_insurance_deduction_mode = 'manual' and nullif(btrim(p_note), '') is null)
    or (p_tax_mode = 'resident_progressive' and nullif(btrim(p_accounting_name), '') is null)
    or (p_tax_mode = 'not_applicable' and not (
      p_dependent_count = 0 and p_burden_mode = 'employee_deducted'
      and p_insurance_deduction_mode = 'none' and p_manual_insurance_deduction_amount = 0
    )) then
    raise exception 'PAYROLL_TAX_SETTING_INVALID' using errcode = '22023';
  end if;
  perform 1 from public.users where id = p_user_id and is_system_account = false;
  if not found then raise exception 'PAYROLL_TAX_SETTING_USER_NOT_FOUND' using errcode = 'P0002'; end if;
  perform pg_advisory_xact_lock(82119, p_user_id::integer);
  select coalesce(max(revision), 0) + 1 into v_revision
  from public.payroll_tax_setting_versions where user_id = p_user_id;
  insert into public.payroll_tax_setting_versions(
    user_id, effective_month, tax_mode, dependent_count, burden_mode,
    accounting_name, insurance_deduction_mode, manual_insurance_deduction_amount,
    revision, created_by, note
  ) values (
    p_user_id, p_effective_month, p_tax_mode, p_dependent_count, p_burden_mode,
    nullif(btrim(p_accounting_name), ''), p_insurance_deduction_mode,
    p_manual_insurance_deduction_amount, v_revision, p_actor_user_id, nullif(btrim(p_note), '')
  ) returning * into v_created;
  return to_jsonb(v_created);
end $$;

