create function public.payroll_refresh_payment_tax_totals_v1(p_run_id bigint)
returns void
language plpgsql
security definer
set search_path=pg_catalog, public
as $$
begin
  update public.payroll_payment_batches b set
    employee_pit_total = x.employee_pit,
    company_pit_total = x.company_pit,
    advance_total = x.advance,
    actual_company_cost_total = x.actual + x.employee_insurance + x.employee_pit + x.advance
      + x.employer_insurance + x.company_pit + b.director_insurance_amount,
    updated_at = now()
  from (
    select
      coalesce(sum(actual_paid_amount), 0)::bigint actual,
      coalesce(sum(employee_insurance_amount), 0)::bigint employee_insurance,
      coalesce(sum(employer_insurance_amount), 0)::bigint employer_insurance,
      coalesce(sum((calculation_snapshot #>> '{employee,tax,employeePitDeductionAmount}')::bigint), 0)::bigint employee_pit,
      coalesce(sum((calculation_snapshot #>> '{employee,tax,companyPitAmount}')::bigint), 0)::bigint company_pit,
      coalesce(sum((calculation_snapshot #>> '{employee,amounts,advanceAmount}')::bigint), 0)::bigint advance
    from public.payroll_employee_payments
    where payroll_batch_id = p_run_id and payment_status = 'paid'
  ) x
  where b.id = p_run_id;
end $$;

