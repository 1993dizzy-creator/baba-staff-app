async function localized(db) {
  const map = {};
  // The tx30-without-party/updated_at fingerprint is the same before and after the correction.
  for (const [prod, query] of Object.entries(FINGERPRINTS)) {
    assert.ok(pre.includes(prod) || exe.includes(prod) || post.includes(prod), prod);
    map[prod] = Object.values((await db.query(query)).rows[0])[0];
  }
  return text => Object.entries(map).reduce((s, [a, b]) => s.replaceAll(a, b), text);
}
const approved = text => text
  .replace("-- SET LOCAL baba.correction_actor_user_id = '1';", "SET LOCAL baba.correction_actor_user_id = '1';")
  .replace("-- SET LOCAL baba.dabaco126_approval = 'APPROVED:aug02-dabaco126-20261104';", "SET LOCAL baba.dabaco126_approval = 'APPROVED:aug02-dabaco126-20261104';");
const checksOf = async (db, sql) => {
  const body = sql.slice(sql.indexOf('WITH\nbal AS'), sql.indexOf('SELECT n, name, ok, actual FROM checks ORDER BY n;') + 'SELECT n, name, ok, actual FROM checks ORDER BY n;'.length);
  return (await db.query(body)).rows;
};
const stateOf = async db => (await db.query(`select md5(string_agg(x,'|' order by x)) f from (
  select 't'||to_jsonb(t)::text x from ledger_transactions t union all select 'm'||to_jsonb(m)::text from ledger_movements m
  union all select 'p'||to_jsonb(p)::text from ledger_payables p union all select 'a'||to_jsonb(a)::text from ledger_payable_allocations a
  union all select 'l'||to_jsonb(l)::text from ledger_audit_logs l) s`)).rows[0].f;
async function runFails(db, sql, code) {
  await assert.rejects(db.exec(sql), new RegExp(code));
  await db.exec('ROLLBACK');
}

test('preflight passes on the reviewed state (21 checks)', async () => {
  const db = await fixture(); const local = await localized(db);
  const rows = await checksOf(db, local(pre));
  assert.equal(rows.length, 21);
  assert.deepEqual(rows.filter(r => !r.ok).map(r => r.name), []);
});

test('execution draft is blocked before any write without the approval value and actor', async () => {
  const db = await fixture(); const local = await localized(db);
  const before = await stateOf(db);
  await runFails(db, local(exe), 'DABACO126_BLOCKED_APPROVAL_REQUIRED');
  const wrongToken = approved(local(exe)).replace("baba.dabaco126_approval = 'APPROVED:aug02-dabaco126-20261104'", "baba.dabaco126_approval = 'yes'");
  await runFails(db, wrongToken, 'DABACO126_BLOCKED_APPROVAL_REQUIRED');
  const noActor = approved(local(exe)).replace("SET LOCAL baba.correction_actor_user_id = '1';", '');
  await runFails(db, noActor, 'DABACO126_BLOCKED_ACTOR_REQUIRED');
  assert.equal(await stateOf(db), before);
});

test('approved execution moves #30 to Dabaco same-day cash, frees #1090 126k and keeps every balance; postflight passes', async () => {
  const db = await fixture(); const local = await localized(db);
  const balances = async () => (await db.query(`select m.fund_account_id a, sum(m.amount)::text s from ledger_movements m join ledger_transactions t on t.id=m.transaction_id
     where t.business_date <= $1 group by 1 order by 1`, ['2026-11-30'])).rows;
  const nov = await balances();
  await db.exec(approved(local(exe)));
  assert.deepEqual(await balances(), nov, 'November (current) balances unchanged');
  const rows = await checksOf(db, local(post));
  assert.equal(rows.length, 16);
  assert.deepEqual(rows.filter(r => !r.ok).map(r => r.name), []);
  const q = async sql => (await db.query(sql)).rows;
  assert.deepEqual(await q(`select party_id, amount::text, category_id from ledger_transactions where id=30`), [{ party_id: 2, amount: '126000.000', category_id: 66 }]);
  assert.deepEqual(await q(`select status from ledger_payables where id=15`), [{ status: 'cancelled' }]);
  assert.deepEqual(await q(`select count(*)::int n from ledger_payable_allocations where id=6`), [{ n: 0 }]);
  const corrections = await q(`select t.business_date::text d, t.correction_of_id c, t.amount::text amt, m.fund_account_id a, m.amount::text mv
     from ledger_transactions t join ledger_movements m on m.transaction_id=t.id where t.type='correction' order by t.id`);
  assert.deepEqual(corrections, [{ d: '2026-08-02', c: 30, amt: '0.000', a: 1, mv: '-126000.000' }, { d: '2026-08-31', c: 1057, amt: '0.000', a: 1, mv: '126000.000' }]);
  const [audit] = await q(`select entity_id, after_snapshot->'changedFields' f, (after_snapshot->>'payment1090Unallocated')::numeric u from ledger_audit_logs where action='august_02_dabaco126_cash_and_okmart_allocation_fixed'`);
  assert.equal(audit.entity_id, 30); assert.equal(Number(audit.u), 126000); assert.equal(audit.f.length, 3);
  // Candidate, inventory log and the real payments are untouched (postflight rows 3/5/6 cover fingerprints).
  assert.deepEqual(await q(`select proposed_party_id from ledger_candidates where id=24`), [{ proposed_party_id: 15 }]);
});

test('re-running after success changes nothing; a partial state is refused', async () => {
  const db = await fixture(); const local = await localized(db);
  await db.exec(approved(local(exe)));
  const after = await stateOf(db);
  await db.exec(approved(local(exe)));
  assert.equal(await stateOf(db), after, 'idempotent: ALREADY_APPLIED, no second correction or audit');
  await db.exec(`DELETE FROM ledger_audit_logs WHERE action='august_02_dabaco126_cash_and_okmart_allocation_fixed'`);
  await runFails(db, approved(local(exe)), 'DABACO126_PARTIAL_OR_FOREIGN_STATE');
});

test('any drift in the protected rows or a closed August rolls back the whole correction', async () => {
  const cases = [
    ['UPDATE ledger_payable_allocations SET allocated_amount = 635000 WHERE id = 25', 'DABACO126_PAYMENT1090_ALLOCATIONS_CHANGED'],
    ['UPDATE ledger_payables SET status = \'partially_paid\' WHERE id = 15', 'DABACO126_PAYABLE15_CHANGED'],
    ['INSERT INTO ledger_movements(transaction_id,fund_account_id,amount) VALUES (200,1,-1)', 'DABACO126_MONTH_END_BALANCES_CHANGED'],
    ['UPDATE ledger_month_closures SET status = \'closed\' WHERE month = \'2026-08-01\'', 'LEDGER_MONTH_CLOSED'],
  ];
  for (const [drift, code] of cases) {
    const db = await fixture(); const local = await localized(db);
    await db.exec(drift);
    const before = await stateOf(db);
    await runFails(db, approved(local(exe)), code);
    assert.equal(await stateOf(db), before, code);
  }
});

