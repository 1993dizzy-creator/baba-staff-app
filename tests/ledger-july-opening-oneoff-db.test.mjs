// Same windows as GET /api/admin/ledger (provisional month): opening rows at the
// month start, otherwise prior confirmed movements; both through fundMovementInScope.
async function balances(db, month) {
  const rows = (await db.query(`select m.fund_account_id, m.amount, t.type, t.business_date::text business_date
    from ledger_movements m join ledger_transactions t on t.id=m.transaction_id where t.status='confirmed'`)).rows;
  const accounts = (await db.query('select id, code from ledger_fund_accounts order by id')).rows;
  const monthStart = `${month}-01`;
  const next = new Date(`${monthStart}T00:00:00Z`); next.setUTCMonth(next.getUTCMonth() + 1);
  const nextMonth = next.toISOString().slice(0, 10);
  const shape = row => ({ fund_account_id: row.fund_account_id, amount: row.amount, transaction: { business_date: row.business_date } });
  const codes = new Map(accounts.map(account => [Number(account.id), account.code]));
  const inScope = row => fundMovementInScope(codes.get(Number(row.fund_account_id)), row.transaction.business_date, month);
  const opening = rows.filter(row => row.type === 'opening' && row.business_date === monthStart).map(shape);
  const prior = opening.length ? [] : rows.filter(row => row.business_date < monthStart).map(shape).filter(inScope);
  const view = buildFundAccountView({
    accounts, openingMovements: opening, priorConfirmedMovements: prior,
    movements: rows.filter(row => row.business_date < nextMonth).map(shape).filter(inScope),
    reservePlans: [], groupReserves: () => new Map(), mode: 'provisional',
  });
  return Object.fromEntries(view.filter(account => BUSINESS.includes(Number(account.id)))
    .map(account => [account.code, { opening: account.openingBalance, balance: account.balance }]));
}
