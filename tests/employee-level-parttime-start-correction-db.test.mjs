    // Sơn October level raise is 0, so the extra-work rate (and its source hash) stays 35,000 VND/h.
    assert.equal(level(29, '2026-10-31').earnedRaiseCount, 0); assert.equal(level(29, '2026-11-30').earnedRaiseCount, 0);
