      assert.equal(n.base_date, base, 'base month unchanged');
      assert.deepEqual(omit(o, 'effective_to'), omit(byId(B, oldId), 'effective_to'));
      assert.deepEqual(omit(n, 'effective_from'), omit(byId(B, newId), 'effective_from'));
