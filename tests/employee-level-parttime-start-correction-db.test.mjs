function extraWork(id, date, minutes, amount) {
  const snapshot = {attendanceRecordId: id, checkInAt: `${date}T09:00:00+00:00`, checkOutAt: `${date}T17:00:00+00:00`, userId: 29, businessDate: date,
    contractId: 26, contractRevision: 2, minuteRateAmount: 35000 / 60, hourlyRateAmount: 35000, scheduleId: 7, scheduleRevision: 1,
    scheduleStartTime: '16:00', scheduleEndTime: '23:30', storeSettingId: 1, storeSettingRevision: 1, storeOpenTime: '16:00', storeCloseTime: '01:00',
    beforeScheduleMinutes: minutes, afterScheduleMinutes: 0, excludedBeforeOpenMinutes: 0, excludedAfterCloseMinutes: 0, candidateMinutes: minutes,
    candidateAmount: amount, extraWorkPolicy: 'part-time-open-early-v1', payType: 'hourly'};
  return {snapshot, hash: createHash('sha256').update(JSON.stringify(snapshot)).digest('hex')};
}
