test('SQL name key equals the app normalizer for accents, tone-mark position, case, spaces and NFD input', async () => {
  const db = await fixture();
  try {
    await db.exec(migration);
    const samples = ['THỦY NAM', 'Thuỷ Nam', '  thuỷ   nam ', 'Thuỷ Nam'.normalize('NFD'), 'ĐẠI PHÁT', 'Đại Phát', 'Coca-Cola 2', ''];
    for (const value of samples) {
      const [{ key }] = await rows(db, 'select business_partner_name_key($1) key', [value]);
      assert.equal(key, normalizeVietnameseText(value) || null, value);
    }
    assert.equal(normalizeVietnameseText('THỦY NAM'), normalizeVietnameseText('Thuỷ Nam'));
    assert.notEqual(normalizeVietnameseText('Thủy Nam'), normalizeVietnameseText('Thủy Nam 2'));
  } finally { await db.close(); }
});

test('create, rename and 등록대기 approval are blocked by an existing partner (active or inactive); the partner itself may be respelled', async () => {
  const db = await fixture();
  try {
    const evidence = async () => ({ partners: await rows(db, 'select id,name,is_active from business_partners order by id'),
      audit: await rows(db, 'select * from business_partner_audit_logs order by 1'), inventory: await rows(db, 'select * from inventory') });
    await db.exec(migration);
    const before = await evidence();
    assert.deepEqual(before.partners.map(row => row.id), [1, 2, 3], 'migration keeps every partner id');
    for (const name of ['THỦY NAM', 'thuy  nam', 'Thuỷ Nam'.normalize('NFD'), 'OLD SHOP', 'öld shop']) {
      assert.equal((await call(db, 'business_partner_create_v4', partnerArgs(name))).status, 'duplicate_name', name);
    }
    assert.deepEqual(await evidence(), before, 'a rejected create writes nothing');
    assert.equal((await call(db, 'business_partner_update_v4', [3, ...partnerArgs('THỦY NAM')])).status, 'duplicate_name');
    assert.equal((await call(db, 'business_partner_update_v4', [1, ...partnerArgs('THỦY NAM')])).status, 'updated', 'own name variant');
    assert.equal((await rows(db, 'select name from business_partners where id=1'))[0].name, 'THỦY NAM');
    // 등록대기 THỦY NAM (#2): a new partner is refused, linking the existing one works.
    assert.equal((await review(db, 2, 'create_partner', 'THỦY NAM')).status, 'duplicate_name');
    assert.equal((await rows(db, 'select status from business_partner_supplier_aliases where id=2'))[0].status, 'pending');
    assert.deepEqual(await review(db, 2, 'link_existing', null, 1), { status: 'reviewed', partnerId: 1, inventoryLinkedCount: 0 });
    // A genuinely different name is still a new partner.
    assert.equal((await call(db, 'business_partner_create_v4', partnerArgs('Thủy Nam 2'))).status, 'created');
    // Concurrent submits / retries: the unique index decides even without the RPC.
    await assert.rejects(db.query("insert into business_partners(name,partner_type,payment_mode,is_active) values('THUY NAM 2','food','postpaid',true)"), /business_partners_name_key_unique/);
  } finally { await db.close(); }
});

test('inventory direct input resolves spelling variants to the existing partner or candidate instead of a new 등록대기', async () => {
  const db = await fixture();
  try {
    await db.exec(migration);
    const aliasCount = async () => (await rows(db, 'select count(*)::int n from business_partner_supplier_aliases'))[0].n;
    const start = await aliasCount();
    for (const name of ['THỦY NAM', 'thuy nam', 'Thuỷ Nam'.normalize('NFD')]) {
      const result = await resolve(db, name);
      assert.equal(result.supplierPartnerId, 1, name);assert.equal(result.supplierName, 'Thuỷ Nam');
    }
    const variant = await resolve(db, 'DAI PHAT');
    assert.deepEqual([variant.supplierAliasId, variant.supplierName, variant.aliasStatus], [3, 'Đại Phát', 'pending']);
    assert.equal(await aliasCount(), start, 'no second candidate for a variant');
    // An inactive partner is never linked automatically; the candidate goes to review, where approval is blocked.
    const inactive = await resolve(db, 'old shop');
    assert.equal(inactive.supplierPartnerId, null);assert.equal(inactive.aliasStatus, 'pending');
    assert.equal((await review(db, inactive.supplierAliasId, 'create_partner', 'old shop')).status, 'duplicate_name');
    // Different names stay separate.
    const other = await resolve(db, 'Thủy Nam 2');
    assert.equal(other.supplierPartnerId, null);assert.equal(other.aliasStatus, 'pending');
    assert.equal(await aliasCount(), start + 2);
    assert.equal((await resolve(db, 'whatever', 1)).supplierPartnerId, 1, 'explicit partner id unchanged');
  } finally { await db.close(); }
});

test('migration stops before indexing when existing partners already collide', async () => {
  const db = await fixture([['Thuỷ Nam', true], ['THỦY NAM2', true]]);
  try {
    await db.exec("update business_partners set name='THỦY NAM' where id=2");
    await assert.rejects(db.exec(migration), /duplicate name keys: thuy nam: #1,#2/);
  } finally { await db.close(); }
});

test('migration writes no partner, inventory, ledger or audit rows', () => {
  const body = migration.replace(/--.*$/gm, '');
  assert.doesNotMatch(body, /(?:update|insert into|delete from)\s+public\.(?:business_partners|inventory|inventory_logs|ledger_\w+|business_partner_audit_logs)\b/i);
});

test('app helpers name the existing partner and only match same-key names', () => {
  const partners = [{ id: 34, name: 'Thuỷ Nam', isActive: true }, { id: 9, name: 'Old Shop', isActive: false }];
  assert.deepEqual(findDuplicatePartner(partners, 'THỦY NAM'), { id: 34, name: 'Thuỷ Nam', isActive: true });
  assert.equal(findDuplicatePartner(partners, 'THỦY NAM', 34), null, 'the edited partner itself');
  assert.equal(findDuplicatePartner(partners, 'Thủy Nam 2'), null);
  assert.equal(findDuplicatePartner(partners, 'old  shop').isActive, false);
  assert.match(duplicatePartnerMessage('ko', partners[0]), /이미 등록된 거래처 "Thuỷ Nam"/);
  assert.match(duplicatePartnerMessage('vi', { ...partners[1], isActive: false }), /"Old Shop" đã được đăng ký \(ngừng dùng\)/);
  const aliases = [{ id: 38, supplierName: 'THỦY NAM', status: 'linked', businessPartnerId: 34 }, { id: 40, supplierName: 'Đại Phát', status: 'pending' }];
  assert.deepEqual(matchExistingSupplier(partners, aliases, 'thuy nam'), { kind: 'partner', id: 34, name: 'Thuỷ Nam' });
  assert.deepEqual(matchExistingSupplier(partners, aliases, 'DAI PHAT'), { kind: 'alias', id: 40, name: 'Đại Phát' });
  assert.equal(matchExistingSupplier(partners, aliases, 'old shop'), null, 'inactive partners are not offered for inventory');
  assert.equal(matchExistingSupplier(partners, aliases, ''), null);
});

