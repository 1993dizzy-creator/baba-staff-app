test("card_clearing (and any non-business or inactive fund) cannot fund an advance; nothing is written", async () => {
  const db = await setup();
  // Active in production, but not a business fund: must be refused.
  assert.equal((await advance(db, REQ_A, { accountId: 4 })).status, "invalid_accounts");
  assert.deepEqual(await counts(db), { adjustments: 0, payments: 1, movements: 0, audits: 0 });
  assert.equal((await db.query("select count(*)::int c from public.ledger_transactions where source_key like '%' || $1", [REQ_A])).rows[0].c, 0);
  // Guard each condition independently.
  await db.exec("insert into public.ledger_fund_accounts(id, type, is_business_fund) values (6, 'card_clearing', true), (7, 'bank', false)");
  await db.exec("insert into public.ledger_fund_accounts(id, type, is_active) values (8, 'cash', false)");
  for (const accountId of [6, 7, 8, 999]) assert.equal((await advance(db, REQ_A, { accountId })).status, "invalid_accounts", String(accountId));
  assert.deepEqual(await counts(db), { adjustments: 0, payments: 1, movements: 0, audits: 0 });
  // A real business fund still works.
  assert.equal((await advance(db, REQ_A, { accountId: 2 })).status, "created");
});
