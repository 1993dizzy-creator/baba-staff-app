test("15/17/18/19: eligibility helper requires the subtype to exist, be active (or already-assigned), and belong to the target partner_type", () => {
  assert.match(migration, /create function public\.business_partner_subtype_is_eligible_v1/);
  const body = migration.slice(migration.indexOf("create function public.business_partner_subtype_is_eligible_v1"), migration.indexOf("alter function public.business_partner_subtype_is_eligible_v1"));
  assert.match(body, /select p_partner_subtype_id is null or exists \(/);
  assert.match(body, /where id = p_partner_subtype_id\s*\n\s*and partner_type = p_partner_type\s*\n\s*and \(is_active = true or id = p_current_subtype_id\)/);

  // Mirrors the SQL above in JS so the eligibility contract is pinned by a fast pure test.
  type Subtype = { id: number; partnerType: string; isActive: boolean };
  const subtypes: Subtype[] = [
    { id: 1, partnerType: "alcohol", isActive: true },
    { id: 2, partnerType: "alcohol", isActive: false },
    { id: 3, partnerType: "food", isActive: true },
  ];
  const isEligible = (subtypeId: number | null, partnerType: string, currentSubtypeId: number | null = null) =>
    subtypeId === null || subtypes.some(s => s.id === subtypeId && s.partnerType === partnerType && (s.isActive || s.id === currentSubtypeId));

  assert.equal(isEligible(null, "alcohol"), true); // 16. null always allowed
  assert.equal(isEligible(1, "alcohol"), true); // active + matching type
  assert.equal(isEligible(2, "alcohol"), false); // 18. inactive, no current-value carve-out -> blocked for new assignment
  assert.equal(isEligible(2, "alcohol", 2), true); // update keeping its own already-assigned inactive subtype
  assert.equal(isEligible(1, "food"), false); // 19. partner_type mismatch -> blocked
  assert.equal(isEligible(999, "alcohol"), false); // nonexistent id
});

