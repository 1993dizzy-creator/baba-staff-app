// Pure-JS mirror of the deployed SQL (business_partner_subtype_is_eligible_v1):
//   select p_partner_subtype_id is null or exists (
//     select 1 from business_partner_subtypes
//     where id = p_partner_subtype_id
//       and partner_type = p_partner_type
//       and (is_active = true or id = p_current_subtype_id)
//   );
// Because the EXISTS subquery is already scoped to `id = p_partner_subtype_id`, the
// `or id = p_current_subtype_id` carve-out only ever fires when the NEW value equals the
// OLD value -- it can never wave through a *different* inactive subtype. update_v4 always
// supplies its own pre-update partner_subtype_id (locked via `for update`) as that 3rd arg;
// create_v4 and the Candidate create_partner branch never supply a 3rd arg at all, so they
// always fall back to the SQL default `null`, which no subtype id can ever equal.
function isSubtypeEligible(
  subtypes: ReadonlyArray<{ id: number; partnerType: string; isActive: boolean }>,
  partnerSubtypeId: number | null,
  partnerType: string,
  currentSubtypeId: number | null = null,
) {
  return partnerSubtypeId === null || subtypes.some(s => s.id === partnerSubtypeId && s.partnerType === partnerType && (s.isActive || s.id === currentSubtypeId));
}

test("required scenarios 1-8: update may only keep its OWN current inactive subtype -- never swap to a different inactive one, and partner_type changes void that carve-out", () => {
  const subtypes = [
    { id: 5, partnerType: "alcohol", isActive: false },  // Partner's current subtype
    { id: 8, partnerType: "alcohol", isActive: true },
    { id: 9, partnerType: "alcohol", isActive: false },  // a *different* inactive subtype
    { id: 20, partnerType: "food", isActive: true },
  ];

  // 1. create_v4 (no current-subtype arg) + inactive -> reject
  assert.equal(isSubtypeEligible(subtypes, 5, "alcohol"), false);
  // 2. review_supplier_alias_v4 create_partner branch (same 2-arg call, no current-subtype id) + inactive -> reject
  assert.equal(isSubtypeEligible(subtypes, 5, "alcohol"), false);
  // 3. update_v4: current inactive subtype resubmitted unchanged (5 -> 5) -> allow
  assert.equal(isSubtypeEligible(subtypes, 5, "alcohol", 5), true);
  // 4. update_v4: current inactive (5) -> a *different* inactive (9) -> reject
  assert.equal(isSubtypeEligible(subtypes, 9, "alcohol", 5), false);
  // 5. update_v4: current inactive (5) -> an active subtype (8) -> allow
  assert.equal(isSubtypeEligible(subtypes, 8, "alcohol", 5), true);
  // 6. update_v4: current inactive (5) -> null -> allow
  assert.equal(isSubtypeEligible(subtypes, null, "alcohol", 5), true);
  // 7. partner_type changed to "food" while resending the stale alcohol-only inactive id (5) -> reject
  assert.equal(isSubtypeEligible(subtypes, 5, "food", 5), false);
  // 8. partner_type changed to "food" + a valid active subtype of the NEW type (20) -> allow
  assert.equal(isSubtypeEligible(subtypes, 20, "food", 5), true);
});

