const rows = async (db, sql, args = []) => (await db.query(sql, args)).rows;
async function rpc(db, kind, policy, actor = 1) {
  const args = ['Partner','food','postpaid',policy.settlementMode,policy.settlementRule,policy.defaultPaymentTermDays,null,null,null,null,null,true,null,actor,policy.settlementDays];
  if (kind === 'update') args.unshift(1);
  if (kind === 'review_supplier_alias') args.splice(0,args.length,1,'create_partner',null,'Candidate','food','postpaid',policy.settlementMode,policy.settlementRule,policy.defaultPaymentTermDays,null,null,null,null,null,actor,policy.settlementDays);
  return (await rows(db, `select business_partner_${kind}_v4(${args.map((_, i) => `$${i+1}`).join(',')}) result`, args))[0].result;
}

test('parser retains precise schedules, rejects malformed combinations and does not infer new terms', () => {
  for (const policy of policies) {
    const parsed = parsePartnerInput({ ...base, ...policy });
    assert.ok(parsed);
    for (const key of Object.keys(policy)) assert.deepEqual(parsed[key], policy[key]);
  }
  for (const policy of invalid) assert.equal(parsePartnerInput({ ...base, ...policy }), null, JSON.stringify(policy));
  assert.equal(parsePartnerInput(base).settlementMode, null);
});

test('local migration and all three atomic RPC paths retain schedules, bridges, audits and authorization', async () => {
  const db = await fixture();
  try {
    const before = await rows(db, 'select to_jsonb(p) row from business_partners p');
    const bridge = await rows(db, 'select * from business_partner_ledger_parties');
    const audit = await rows(db, 'select * from business_partner_audit_logs');
    await db.exec(migration);
    assert.deepEqual(await rows(db, "select to_jsonb(p)-'settlement_days' row from business_partners p"), before);
    assert.deepEqual(await rows(db, 'select * from business_partner_ledger_parties'), bridge);
    assert.deepEqual(await rows(db, 'select * from business_partner_audit_logs'), audit);
    for (const policy of policies) {
      assert.equal((await rpc(db, 'update', policy)).status, 'updated');
      const saved = (await rows(db, 'select settlement_mode,settlement_rule,default_payment_term_days,settlement_days from business_partners where id=1'))[0];
      assert.deepEqual(saved, { settlement_mode: policy.settlementMode, settlement_rule: policy.settlementRule, default_payment_term_days: policy.defaultPaymentTermDays, settlement_days: policy.settlementDays });
      assert.deepEqual(await rows(db, 'select * from business_partner_ledger_parties'), bridge);
    }
    for (const policy of invalid) assert.equal((await rpc(db, 'update', policy)).status, 'invalid_input', JSON.stringify(policy));
    assert.equal((await rpc(db, 'update', policies[2], 2)).status, 'forbidden');
    await db.exec("update business_partners set name='Updated' where id=1");
    assert.equal((await rpc(db, 'create', policies[2])).status, 'created');
    assert.equal((await rpc(db, 'review_supplier_alias', policies[4])).status, 'reviewed');
    assert.deepEqual((await rows(db, "select settlement_rule,settlement_days from business_partners where name='Candidate'"))[0], { settlement_rule: 'monthly_twice', settlement_days: [15,0] });
    const candidateAudit = (await rows(db, "select after_snapshot from business_partner_audit_logs where after_snapshot->>'name'='Candidate'"))[0];
    assert.deepEqual(candidateAudit.after_snapshot.settlement_days, [15,0]);
    assert.equal((await rows(db, 'select supplier_partner_id from inventory where id=1'))[0].supplier_partner_id, candidateAudit.after_snapshot.id);
    for (const name of ['create','update','review_supplier_alias']) {
      const functions = await rows(db, 'select prosecdef,proconfig,proacl::text acl from pg_proc where proname=$1', [`business_partner_${name}_v4`]);
      assert.equal(functions.length, 1, 'no ambiguous RPC overloads');
      assert.equal(functions[0].prosecdef, true);
      assert.ok(functions[0].proconfig.includes('search_path=pg_catalog, public'));
      assert.match(functions[0].acl, /service_role=X/);
      assert.doesNotMatch(functions[0].acl, /anon=|authenticated=|\{=X/);
    }
  } finally { await db.close(); }
});

