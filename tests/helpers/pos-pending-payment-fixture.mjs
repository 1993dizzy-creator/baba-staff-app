import { readFileSync } from 'node:fs';

export const pendingMigration = readFileSync('supabase/migrations/20261022120000_pos_pending_payment_close_hold.sql', 'utf8');

const CLOSE = 'public.sales_close_business_day_v1(date,text,jsonb,jsonb,bigint,text,boolean,bigint)';
const LOCK_THEN_VALIDATE = /(in share mode;)(\r?\n)(  perform pos_sales_close_private\.validate_source\()/;

// The live production close body has one blank line between the share lock and
// validate_source (the repository migrations do not). Reproduce that layout, keeping
// the body's own line endings, so the migration anchor is tested against production.
export async function applyProductionCloseLayout(db) {
  const def = (await db.query('select pg_get_functiondef($1::regprocedure) d', [CLOSE])).rows[0].d;
  if (LOCK_THEN_VALIDATE.test(def)) await db.exec(def.replace(LOCK_THEN_VALIDATE, '$1$2$2$3'));
}

// Production receipt columns the pending-payment migration touches, on top of the
// minimal close fixture, then the migration file exactly as it would be applied.
export async function installPendingPaymentMigration(db, { productionLayout = true } = {}) {
  if (productionLayout) await applyProductionCloseLayout(db);
  await db.exec(`
    alter table pos_sales_receipts add column source text default 'cukcuk', add column ref_id text,
      add column status_changed_at timestamptz, add column receive_amount numeric, add column return_amount numeric,
      add column is_modified boolean default false, add column modified_at timestamptz, add column modified_by text,
      add column modification_note text, add column inventory_deduction_auto_eligible_at timestamptz,
      add column inventory_deduction_processing_paused boolean default false,
      add column inventory_deduction_processing_paused_at timestamptz, add column inventory_deduction_processing_error text,
      add column inventory_deduction_last_checked_at timestamptz, add column inventory_deduction_pending_fingerprint text,
      add column inventory_deduction_pending_status text;
    update pos_sales_receipts set ref_id = 'ref-' || id;
    create sequence pos_sales_receipt_payments_id_seq start 1000;
    alter table pos_sales_receipt_payments alter column id set default nextval('pos_sales_receipt_payments_id_seq'),
      add column source text default 'cukcuk', add column receipt_ref_id text, add column ref_date timestamptz,
      add column card_id text, add column raw_json jsonb, add column synced_at timestamptz, add column updated_at timestamptz;
    create table public.pos_sales_receipt_lines(id bigint generated by default as identity primary key,
      receipt_id bigint references pos_sales_receipts(id), payment_status integer, is_canceled boolean, updated_at timestamptz);
    create table public.pos_sales_receipt_modifications(id bigint generated by default as identity primary key,
      receipt_id bigint not null references pos_sales_receipts(id), request_id uuid not null, revision_before bigint not null,
      revision_after bigint not null, modified_by text not null, modification_note text, before_state jsonb not null,
      after_state jsonb not null, result jsonb not null, created_at timestamptz not null default now(), unique(receipt_id, request_id));
  `);
  await db.exec(pendingMigration);
}

// Pending receipt 9 (status 1) on the given date, with a stale CUKCUK payment snapshot row.
export async function addPendingReceipt(db, date, { id = 9, amount = 50000, pendingSince = "now() - interval '45 minutes'", canceled = false } = {}) {
  await db.exec(`insert into pos_sales_receipts(id,ref_no,ref_id,business_date,ref_date,payment_status,is_canceled,final_amount,revision,updated_at)
    values (${id},'P${id}','ref-${id}','${date}',${pendingSince},1,${canceled},${amount},0,now());
    insert into pos_sales_receipt_payments(receipt_id,business_date,payment_type,payment_name,amount,source)
    values (${id},'${date}',1,'Khác',${amount},'cukcuk');
    insert into pos_sales_receipt_lines(receipt_id,payment_status,is_canceled) values (${id},1,${canceled}),(${id},1,${canceled});`);
}

export async function resolvePending(db, args) {
  const { id = 9, revision = 0, requestId, actor = 'manager', resolution = 'paid', method = 'transfer', cash = null,
    note = 'Bank transfer #123 confirmed' } = args;
  return (await db.query('select admin_resolve_pending_sales_receipt_v1($1,$2,$3,$4,$5,$6,$7,$8) result',
    [id, revision, requestId, actor, resolution, method, cash, note])).rows[0].result;
}

export async function functionIdentity(db, signature) {
  return (await db.query(`select oid::int oid, proowner::int owner, proacl::text acl, prosecdef, proconfig::text config
    from pg_proc where oid = $1::regprocedure`, [signature])).rows[0];
}
