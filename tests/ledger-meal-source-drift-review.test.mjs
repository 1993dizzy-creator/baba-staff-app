async function closeAdjustmentMonth(db) {
  // Keep the source month open and distinct from the adjustment month on any test date.
  await db.exec(`
    update ledger_transactions set
      recognition_month=(date_trunc('month',(now() at time zone 'Asia/Ho_Chi_Minh')-interval '3 hours')-interval '1 month')::date,
      business_date=(date_trunc('month',(now() at time zone 'Asia/Ho_Chi_Minh')-interval '3 hours')-interval '1 month')::date;
    insert into closed_months values(date_trunc('month',(now() at time zone 'Asia/Ho_Chi_Minh')-interval '3 hours')::date);
  `);
}

