async function database(original = 330000, effective = original, latest = 360000) {
  const db = new PGlite();
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create table public.users(id bigint primary key,role text,is_active boolean,app_login_enabled boolean);
    create table public.ledger_categories(id bigint primary key,name text,kind text);
    create table public.ledger_transactions(
      id bigint generated by default as identity primary key,operation_id uuid,type text,
      occurred_at timestamptz,business_date date,recognition_month date,amount numeric,
      category_id bigint,party_id bigint,status text,source_type text,source_key text,
      source_snapshot jsonb,source_fingerprint text,source_synced_at timestamptz,
      correction_of_id bigint,memo text,created_by bigint,confirmed_by bigint,economic_effect_sign int,
      display_snapshot jsonb not null default '{}'::jsonb
    );
    create table public.ledger_candidates(id bigint primary key,candidate_type text,source_type text,status text,
      resolved_transaction_id bigint,source_snapshot jsonb,source_drift_snapshot jsonb,source_drift_fingerprint text);
    create table public.ledger_movements(id bigint generated always as identity primary key,transaction_id bigint,fund_account_id bigint,amount numeric);
    create table public.ledger_audit_logs(id bigint generated always as identity primary key,
      actor_user_id bigint,action text,entity_type text,entity_id bigint,before_snapshot jsonb,after_snapshot jsonb,reason text);
    create table public.ledger_fund_accounts(id bigint primary key,code text,is_active boolean,is_business_fund boolean,active_from date,active_to date);
    create table public.closed_months(month date primary key);
    create function public.ledger_month_is_closed_v1(p_month date) returns boolean language sql as $$
      select exists(select 1 from public.closed_months where month=p_month) $$;
    insert into public.users values(1,'owner',true,true),(2,'staff',true,true),(3,'master',true,true);
    insert into public.ledger_categories values(7,'직원 식대','expense');
    insert into public.ledger_fund_accounts values(5,'store_cash',true,true,'2026-01-01',null);
  `);
  await db.query(`insert into ledger_transactions(id,type,business_date,recognition_month,amount,category_id,status,source_type,source_key,source_snapshot,source_fingerprint,economic_effect_sign,display_snapshot)
    values(2135,'expense','2026-09-30','2026-09-01',$1,7,'confirmed','attendance_meal_daily_candidate','candidate:7',$2,$3,1,'{"preserved":"display"}')`,
    [original,{ total_amount: original, employee_count: original / 30000 },fp('a')]);
  await db.query(`insert into ledger_candidates values(7,'employee_meal','attendance_meal_daily','confirmed',2135,$1,$2,$3)`,
    [{ total_amount: original, employee_count: original / 30000 },latest == null ? null : { total_amount: latest, employee_count: latest / 30000 },latest == null ? null : fp('b')]);
  await db.query('insert into ledger_movements(transaction_id,fund_account_id,amount) values(2135,5,$1)',[-original]);
  if (effective !== original) {
    await db.query(`insert into ledger_transactions(id,type,business_date,recognition_month,amount,category_id,status,source_type,correction_of_id,source_snapshot,economic_effect_sign)
      values(2147,'expense','2026-09-30','2026-09-01',$1,7,'confirmed','ledger_correction',2135,'{"adjustmentType":"employee_meal"}',$2)`,[Math.abs(effective-original),effective>original?1:-1]);
    await db.query('insert into ledger_movements(transaction_id,fund_account_id,amount) values(2147,5,$1)',[original-effective]);
  }
  await db.exec(migration);
  return db;
}
async function save(db, amount, reason = 'Actual expenditure checked', actor = 1) {
  return (await db.query('select public.ledger_adjust_open_meal_transaction_v1(2135,$1,$2,$3) as result',[amount,reason,actor])).rows[0].result;
}
async function counts(db) {
  return (await db.query(`select (select count(*)::int from ledger_transactions) as transactions,
    (select count(*)::int from ledger_movements) as movements,(select count(*)::int from ledger_audit_logs) as audits`)).rows[0];
}
async function entry(db) {
  const transactions = (await db.query('select *,business_date::text as business_date,recognition_month::text as recognition_month,occurred_at::text as occurred_at from ledger_transactions')).rows;
  const candidate = (await db.query('select * from ledger_candidates where id=7')).rows[0];
  return buildLedgerEntries(transactions,[],new Map(),[{
    resolvedTransactionId:2135,sourceSnapshot:candidate.source_snapshot,
    sourceDriftSnapshot:candidate.source_drift_snapshot,sourceDriftFingerprint:candidate.source_drift_fingerprint,
  }]).find(row=>row.transactionId===2135);
}
test('production 360 + manual 30 / latest 360 is non-economic drift without resaving',async()=>{
  const db=await database(360000,390000,360000);
  try {
    const before=await counts(db);
    const row=await entry(db);
    assert.equal(row.requiresCorrection,false);
    assert.equal(row.originalAmount,360000);
    assert.equal(row.adjustmentAmount,30000);
    assert.equal(row.effectiveAmount,390000);
    assert.equal(row.adjustmentCount,1);
    assert.equal((await save(db,390000)).status,'unchanged');
    assert.deepEqual(await counts(db),before);
  } finally { await db.close(); }
});
test('economic drift review creates exactly one +60 correction, then a new fingerprint reopens review',async()=>{
  const db=await database();
  try {
    assert.equal((await entry(db)).requiresCorrection,true);
    const original=(await db.query('select * from ledger_transactions where id=2135')).rows[0];
    const candidateBefore=(await db.query('select * from ledger_candidates where id=7')).rows[0];
    const before=await counts(db);
    const result=await save(db,390000);
    assert.equal(result.status,'created');
    assert.equal(result.economicDelta,60000);
    assert.equal(result.storeCashMovement,-60000);
    assert.equal((await counts(db)).transactions,before.transactions+1);
    assert.equal((await counts(db)).movements,before.movements+1);
    const correction=(await db.query('select * from ledger_transactions where correction_of_id=2135')).rows;
    assert.equal(correction.length,1);
    assert.equal(Number(correction[0].amount),60000);
    assert.equal(Number(correction[0].economic_effect_sign),1);
    assert.equal(correction[0].source_snapshot.reviewedSourceDriftFingerprint,fp('b'));
    assert.equal((await entry(db)).effectiveAmount,390000);
    assert.equal((await entry(db)).requiresCorrection,false);
    const after=(await db.query('select * from ledger_transactions where id=2135')).rows[0];
    assert.deepEqual({...after,display_snapshot:original.display_snapshot},original);
    assert.equal(after.display_snapshot.preserved,'display');
    assert.deepEqual((await db.query('select * from ledger_candidates where id=7')).rows[0],candidateBefore);
    const stable=await counts(db);
    assert.equal((await save(db,390000)).status,'unchanged');
    assert.deepEqual(await counts(db),stable);
    await db.query('update ledger_candidates set source_drift_snapshot=$1,source_drift_fingerprint=$2 where id=7',[{total_amount:370000},fp('c')]);
    assert.equal((await entry(db)).requiresCorrection,true);
  } finally { await db.close(); }
});
test('maintaining current amount reviews genuine drift with metadata and audit only, idempotently',async()=>{
  const db=await database(330000,390000,360000);
  try {
    assert.equal((await entry(db)).requiresCorrection,true);
    const before=await counts(db);
    const movementsBefore=(await db.query('select * from ledger_movements order by id')).rows;
    assert.equal((await save(db,390000,'Keep verified sheet actual',3)).status,'reviewed');
    assert.deepEqual(await counts(db),{...before,audits:before.audits+1});
    assert.deepEqual((await db.query('select * from ledger_movements order by id')).rows,movementsBefore);
    const metadata=(await db.query('select display_snapshot from ledger_transactions where id=2135')).rows[0].display_snapshot;
    assert.equal(metadata.mealSourceDriftReviewedFingerprint,fp('b'));
    assert.ok(metadata.mealSourceDriftReviewedAt);
    const audit=(await db.query('select * from ledger_audit_logs')).rows[0];
    assert.equal(Number(audit.actor_user_id),3);
    assert.equal(audit.reason,'Keep verified sheet actual');
    assert.equal(audit.action,'meal_source_drift_reviewed');
    assert.equal(audit.after_snapshot.currentDriftFingerprint,fp('b'));
    assert.equal(audit.after_snapshot.finalAmount,390000);
    assert.equal(audit.after_snapshot.economicDelta,0);
    assert.equal((await entry(db)).requiresCorrection,false);
    assert.equal((await save(db,390000)).status,'unchanged');
    assert.deepEqual(await counts(db),{...before,audits:before.audits+1});
    // Same latest total, new attendance fingerprint: requires a fresh review.
    await db.query('update ledger_candidates set source_drift_fingerprint=$1 where id=7',[fp('c')]);
    assert.equal((await entry(db)).requiresCorrection,true);
  } finally { await db.close(); }
});
