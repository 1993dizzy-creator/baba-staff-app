test('a downstream movement failure rolls back review metadata, audits and correction together', async () => {
  const db = await database();
  try {
    await db.exec(`create function reject_movement() returns trigger language plpgsql as $$
      begin raise exception 'TEST_MOVEMENT_REJECTED'; end $$;
      create trigger reject_movement before insert on ledger_movements for each row execute function reject_movement();`);
    const before = await counts(db);
    const original = (await db.query('select * from ledger_transactions where id=2135')).rows[0];
    await assert.rejects(save(db,390000),/TEST_MOVEMENT_REJECTED/);
    assert.deepEqual(await counts(db),before);
    assert.deepEqual((await db.query('select * from ledger_transactions where id=2135')).rows[0],original);
    assert.equal((await entry(db)).requiresCorrection,true);
  } finally { await db.close(); }
});
