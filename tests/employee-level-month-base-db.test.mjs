test('same-month update keeps the full previous version row; raise-only change is audited separately; no-op writes nothing', async () => {
  const db = await database();
  try {
    await v10(db, { userId: 5, mode: 'hire_month', reason: 'first_change' });
    const firstRevision = (await versions(db, 5)).at(-1).revision;
    await v10(db, { userId: 5, mode: 'hire_month', raise: false, reason: 'second_change' });
    const rows = await versions(db, 5);
    assert.equal(rows.at(-1).revision, firstRevision, 'same effective month updates in place');
    assert.equal(rows.at(-1).salary_raise_enabled, false);
    const audit = (await db.query(`select action, previous_salary_raise_enabled, next_salary_raise_enabled, previous_version_snapshot, next_version_snapshot
      from employee_level_audit_logs where user_id = 5 order by id`)).rows;
    const last = audit.at(-1);
    assert.equal(last.action, 'level_salary_raise_changed');
    assert.deepEqual([last.previous_salary_raise_enabled, last.next_salary_raise_enabled], [true, false]);
    assert.equal(last.previous_version_snapshot.change_reason, 'first_change');
    assert.equal(last.previous_version_snapshot.salary_raise_enabled, true);
    assert.equal(last.next_version_snapshot.change_reason, 'second_change');
    const count = audit.length;
    await v10(db, { userId: 5, mode: 'hire_month', raise: false });
    assert.equal((await db.query('select count(*)::int n from employee_level_audit_logs where user_id = 5')).rows[0].n, count);
    // NULL raise keeps the decision in force.
    await v10(db, { userId: 5, mode: 'hire_month', raise: null });
    assert.equal((await versions(db, 5)).at(-1).salary_raise_enabled, false);
  } finally { await db.close(); }
});

