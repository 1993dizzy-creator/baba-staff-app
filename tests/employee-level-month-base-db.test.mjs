const user = async (db, id) => (await db.query(`select level_program_enabled, level_base_date_override::text, level_base_mode from users where id = $1`, [id])).rows[0];

test('migration keeps every legacy version, audit row and payroll payment byte-identical', async () => {
  const db = new PGlite();
  try {
    await db.exec(FIXTURE);
    // Seed, measure, apply the draft, measure again.
    await db.exec(`
      insert into users(id, username, password, name, role, hire_date, level_program_enabled, level_base_date_override) values (1, 'han', 'x', 'HAN', 'master', '2025-09-06', false, null), (6, 'linh', 'x', 'Linh H', 'leader', '2025-12-03', true, '2026-01-03');
      insert into employee_level_program_versions(user_id, enabled, effective_from, effective_to, base_date, base_date_mode, revision, change_reason, created_by, created_by_username) values (6, true, '2026-08-01', null, '2026-01-03', 'override', 2, 'admin_level_base_override', 1, 'han');
      insert into employee_level_audit_logs(user_id, action, actor_username, change_reason) values (6, 'level_base_date_changed', 'han', 'legacy');
      insert into payroll_employee_payments values (100, 6, '{"levelSnapshot":{"level":2}}', 'abc', 14000000, 'paid');`);
    const legacyCols = 'id, user_id, enabled, effective_from, effective_to, base_date, base_date_mode, revision, change_reason, created_by, created_by_username, created_at';
    const before = [await snapshot(db, `select ${legacyCols} from employee_level_program_versions order by id`),
      await snapshot(db, 'select * from employee_level_audit_logs order by id'),
      await snapshot(db, 'select * from payroll_employee_payments order by id'),
      await snapshot(db, 'select id, hire_date, level_program_enabled, level_base_date_override from users order by id')];
    await db.exec(DRAFT);
    const auditCols = 'id, user_id, action, previous_enabled, next_enabled, previous_base_date_override, next_base_date_override, previous_effective_base_date, next_effective_base_date, previous_level, next_level, actor_id, actor_username, change_reason, created_at, previous_base_date_mode, next_base_date_mode';
    const after = [await snapshot(db, `select ${legacyCols} from employee_level_program_versions order by id`),
      await snapshot(db, `select ${auditCols} from employee_level_audit_logs order by id`),
      await snapshot(db, 'select * from payroll_employee_payments order by id'),
      await snapshot(db, 'select id, hire_date, level_program_enabled, level_base_date_override from users order by id')];
    assert.deepEqual(after, before);
    // New columns default to "previous behaviour": raise on, no month mode.
    assert.deepEqual((await db.query('select salary_raise_enabled from employee_level_program_versions')).rows, [{ salary_raise_enabled: true }]);
    assert.deepEqual((await db.query('select level_base_mode from users order by id')).rows, [{ level_base_mode: null }, { level_base_mode: null }]);
  } finally { await db.close(); }
});

test('v10 direct base month: HAI LINH 2026-02 (hire 2025-12-03) is stored as 2026-02-01; month = hire month allowed; before hire month refused', async () => {
  const db = await database();
  try {
    await v10(db, { userId: 6, mode: 'override_month', override: '2026-02-01' });
    const rows = await versions(db, 6);
    assert.deepEqual(rows.at(-1).base_date, '2026-02-01');
    assert.equal(rows.at(-1).base_date_mode, 'override_month');
    assert.deepEqual(await user(db, 6), { level_program_enabled: true, level_base_date_override: '2026-02-01', level_base_mode: 'override_month' });
    // Previous versions are not rewritten (only the version in force is closed at the month).
    assert.deepEqual(rows.slice(0, 2).map((r) => [r.base_date, r.base_date_mode]), [['2025-12-03', 'hire_date'], ['2026-01-03', 'override']]);
    // Hire month itself (2025-12-01 < hire day 3) is allowed for month modes.
    await v10(db, { userId: 6, mode: 'override_month', override: '2025-12-01' });
    assert.equal((await user(db, 6)).level_base_date_override, '2025-12-01');
    await assert.rejects(v10(db, { userId: 6, mode: 'override_month', override: '2025-11-01' }), /BASE_MONTH_BEFORE_HIRE_MONTH/);
    await assert.rejects(v10(db, { userId: 6, mode: 'override_month', override: '2026-02-15' }), /INVALID_BASE_MONTH/);
    await assert.rejects(v10(db, { userId: 6, mode: 'override_month', override: null }), /INVALID_BASE_MONTH/);
  } finally { await db.close(); }
});

