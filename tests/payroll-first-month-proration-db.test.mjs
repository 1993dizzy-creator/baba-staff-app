test('payment evidence guard preserves paid/cancelled history and permits normal close-first payment',async()=>{
  const db=await database();try {
    const u=await create(db),c=(await link(db,u.id)).contract;
    await db.exec(`insert into payroll_payment_batches values(1,'2026-11-01','paying');insert into ledger_month_closures(month,status) values('2026-11-01','closed');`);
    await assert.rejects(pay(db,u,c,{amount:8000000}),/FIRST_MONTH_POLICY_REVIEW_REQUIRED/);
    await pay(db,u,c);const before=await state(db);
    assert.equal((await link(db,u.id)).status,'created');assert.deepEqual(await state(db),before);
    assert.equal((await correct(db,u.id,'2026-11-16','2026-11-16')).status,'policy_locked');
    await db.exec(`insert into payroll_payment_audit_logs(employee_payment_id,payroll_batch_id,action,before_snapshot) select id,1,'employee_payment_cancelled',to_jsonb(p) from payroll_employee_payments p;
      update payroll_employee_payments set payment_status='unpaid' where id=100;delete from ledger_month_closures;`);
    assert.equal((await correct(db,u.id,'2026-11-16','2026-11-16')).status,'policy_locked');
    await assert.rejects(pay(db,u,c),/duplicate/);
    // No rewriting of the original cancelled snapshot/hash.
    assert.equal((await db.query('select calculation_hash from payroll_employee_payments where id=100')).rows[0].calculation_hash,'original-hash');
  }finally{await db.close();}
});
