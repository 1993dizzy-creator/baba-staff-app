test('formal migration preserves all old rows and never enrolls old or legacy-path new employees',async()=>{
  const db=await database({apply:false});try {
    const before=await state(db);await db.exec(migration);assert.deepEqual(await state(db),before);
    assert.deepEqual(await policies(db),[]);
    await create(db,'old-path','2026-11-16','employee_create_with_schedule_v6');assert.deepEqual(await policies(db),[]);
    assert.equal((await link(db,2)).status,'policy_not_registered');
  }finally{await db.close();}
});
test('new creation and pending enrollment are atomic; first contract activates once and survives lost response/reload retries',async()=>{
  const db=await database();try {
    const u=await create(db);assert.equal((await policies(db))[0].status,'pending');
    const first=await link(db,u.id);assert.equal(first.status,'created');
    for(let i=0;i<3;i++)assert.deepEqual(await link(db,u.id),first);
    assert.equal((await policies(db))[0].status,'active');
    assert.equal((await db.query('select count(*)::int n from payroll_contract_versions')).rows[0].n,1);
    await assert.rejects(create(db),/duplicate/);assert.equal((await policies(db)).length,1);
    const before=await state(db);
    await db.exec(`create function reject_policy() returns trigger language plpgsql as $$begin raise exception 'TEST_POLICY_FAILURE';end$$;
      create trigger reject_policy before insert on payroll_first_month_policies for each row execute function reject_policy();`);
    await assert.rejects(create(db,'failed'),/TEST_POLICY_FAILURE/);assert.deepEqual(await state(db),before);
  }finally{await db.close();}
});
